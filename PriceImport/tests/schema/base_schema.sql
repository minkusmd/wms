CREATE PROCEDURE SP_CREATE_NEW_DOCUMENT (DT INTEGER, CT INTEGER, DTDEP INTEGER, CTDEP INTEGER, DTSC INTEGER,
  CTSC INTEGER, SUMA NUMERIC(18,2), VAT NUMERIC(18,2), CURRENCYID INTEGER, DISCOUNT NUMERIC(18,2),
  RATE DOUBLE PRECISION, RATEUSD DOUBLE PRECISION, PARENTDOCID INTEGER, ACC$MASK INTEGER, DOCTYPEID INTEGER,
  FLAGS INTEGER, SC2 INTEGER, CONTRACTID INTEGER)
RETURNS (NEWDOCID INTEGER)
AS
declare created_by integer;
begin
  :newdocid = -1;
   created_by = coalesce(rdb$get_context('USER_SESSION','UserID'), 9);
   insert into TDB_DOCS (DT, CT, DTDEP, CTDEP, DTSC, ctsc, SUMA, VAT, CURRENCYID, DISCOUNT, RATE, RATEUSD, PARENTDOCID,
                         ACC$MASK, DOCTYPEID, FLAGS, SC2, CONTRACTID, created_by)
   VALUES (:dt, :ct, :DTDEP, :CTDEP, :DTSC, :ctsc, :SUMA, :VAT, :CURRENCYID, :DISCOUNT, :RATE, :RATEUSD, -1,
           :ACC$MASK, :doctypeid, :flags, :SC2, :CONTRACTID, :created_by)
   returning DOCID into :NEWDOCID;
  suspend;
end^

CREATE PROCEDURE ADJUST_RRP_REEVALUATION (DOCID INTEGER, PERCENT NUMERIC(6,3))
AS
begin
  rdb$set_context('USER_SESSION', 'UserID', 204);
  rdb$set_context('USER_TRANSACTION', 'RequireModifyDOC', 1);
  update tdb_goods_price
    set price3 = ceil(round(price3 - abs(price3 / 100 * :percent)))
  where docid = :docid and get_flg_value(flags, 4) = 1;
end^

CREATE PROCEDURE CLOSE_REEVALUARE (DOCID INTEGER)
AS
declare variable customerid integer;
declare variable goodsid integer;
declare variable code varchar(128);
declare variable price0 double precision;
declare variable price3 double precision;
declare variable price7 double precision;
declare variable cur3 integer;
declare variable cur7 integer;
declare variable flags integer;
begin
  select CT from TDB_DOCS where DOCID = :DOCID into :CUSTOMERID;
  for select GOODSID, SUPPLIER_GOODS_CODE, PRICE0, PRICE3, PRICE7, CURRENCY3ID, CURRENCY7ID, FLAGS
      from TDB_GOODS_PRICE where DOCID = :DOCID
      into :goodsid, :code, :price0, :price3, :price7, :cur3, :cur7, :flags
  do
  begin
    update TS_GOODS_FOREIGN set PRICE7 = :price7, CURRENCY7ID = :cur7,
      PRICE0 = iif(coalesce(:price0, 0) > 0, :price0, PRICE0), CURRENCY0ID = :cur7,
      PRICE3 = iif(coalesce(:price3, 0) = 0, 0, :price3), CURRENCY3ID = coalesce(:cur3, CURRENCY3ID),
      FLAGS = set_flg_value(set_flg_value(FLAGS, 3, get_flg_value(:flags, 3)), 4,
                            iif(coalesce(:price3, 0) = 0, 0, get_flg_value(:flags, 4)))
    where GOODSID = :goodsid and CUSTOMERID = :customerid and GOODS_CODE = :code;
    if (code starting with 'BAD') then
      exception err_general_error 'goodscode: ' || :code || ' [Formula: nan]';
  end
  update tdb_docs set flags = set_flg_value(coalesce(flags, 0), 10, 1) where docid = :docid;
end^

SET TERM ; ^
COMMIT;

