  PRIORITY     INTEGER = 0)
SQL SECURITY DEFINER
AS
BEGIN
  INSERT INTO TELEGRAM_MESSAGES (CHANNEL_CODE, MSG_TEXT, PARSE_MODE, SOURCE_TABLE, SOURCE_ID, PRIORITY)
  VALUES (:CHANNEL_CODE, :MSG_TEXT, :PARSE_MODE, :SOURCE_TABLE, :SOURCE_ID, :PRIORITY);
END^

