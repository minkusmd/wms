CREATE TRIGGER TS_PRICELISTS_BI FOR TS_PRICELISTS ACTIVE BEFORE INSERT POSITION 0
AS
begin
  if (new.plid is null) then
    new.plid = gen_id(gen_ts_pricelists_id, 1);
  new.data = coalesce(new.data, current_timestamp);
  NEW.CREATED_BY = RDB$GET_CONTEXT('USER_SESSION', 'UserID');
end^

CREATE TRIGGER TDB_GOODS_PRICE_BI FOR TDB_GOODS_PRICE ACTIVE BEFORE INSERT POSITION 0
AS
declare variable customerid integer;
begin
  select ct from tdb_docs where docid = new.docid into :customerid;
  new.currencyid = coalesce(new.currencyid, new.currency7id);
  new.modified_by = RDB$GET_CONTEXT('USER_SESSION', 'UserID');
  if (coalesce(new.price7, 0) = 0) then
    select PRICE7, currency7id from TS_GOODS_FOREIGN
    where GOODSID = new.GOODSID and GOODS_CODE = new.SUPPLIER_GOODS_CODE and CUSTOMERID = :CUSTOMERID
    into new.PRICE7, new.currency7id;
  /* bitii 3 (in pricelist) si 4 (EPP) vin din randul inserat, ca in triggerul real */
  new.flags = set_flg_value(set_flg_value(0, 3, get_flg_value(new.flags, 3)), 4, get_flg_value(new.flags, 4));
end^

