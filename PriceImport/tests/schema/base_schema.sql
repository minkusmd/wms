CREATE FUNCTION GET_FLG_IN_PRICE (GOODSID INTEGER) RETURNS INTEGER
AS
begin
  return iif(exists(select GOODSID
                    from TDB_GOODS_FLAGS
                    where (TDB_GOODS_FLAGS.GOODSID = :GOODSID)
                          and ((FLAGTYPEID = 3) or (FLAGTYPEID = 5 and VALUE_INT = 1))
                          and (DT = 5213)), 1, 0);
end^

