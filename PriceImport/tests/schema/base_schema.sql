CREATE FUNCTION GET_FLG_VALUE (AFLAG INTEGER, ABITINDEX INTEGER) RETURNS INTEGER
AS
BEGIN
   RETURN bin_and(bin_shr(coalesce(:aflag,0), :abitindex), 1);
END^

CREATE FUNCTION SET_FLG_VALUE (AFLAG INTEGER, ABITINDEX INTEGER, ABITVALUE INTEGER) RETURNS INTEGER
AS
BEGIN
  IF (:ABITVALUE > 0) THEN
    RETURN coalesce(BIN_OR(coalesce(:AFLAG,0), BIN_SHL(1, :ABITINDEX)),0);
  ELSE
    RETURN coalesce(BIN_AND(coalesce(:AFLAG,0), BIN_NOT(BIN_SHL(1, :ABITINDEX))),0);
END^

