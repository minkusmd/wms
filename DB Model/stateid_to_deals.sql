/* --- 3-4. Arhive (create o singura data, nu se suprascriu) ----------------------- */
EXECUTE BLOCK AS
BEGIN
    IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE TRIM(RDB$RELATION_NAME) = 'TARC_DOCS_STATES')) THEN
    BEGIN
        EXECUTE STATEMENT
        'CREATE TABLE TARC_DOCS_STATES (
             DOCID        INTEGER NOT NULL,
             DOCTYPEID    INTEGER,
             STATEID      INTEGER,
             TITLE        VARCHAR(200),
             ARCHIVED_AT  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
             CONSTRAINT PK_TARC_DOCS_STATES PRIMARY KEY (DOCID)
         )';
    END

    IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE TRIM(RDB$RELATION_NAME) = 'TARC_DEALS_BEFORE_STATEID')) THEN
    BEGIN
        EXECUTE STATEMENT
        'CREATE TABLE TARC_DEALS_BEFORE_STATEID (
             DEAL_ID           BIGINT NOT NULL,
             PIPE_STATE_ID     INTEGER,
             FIN_STATE_ID      INTEGER,
             CANCEL_REASON_ID  INTEGER,
             CHANNEL_ID        INTEGER,
             CLOSED_AT         TIMESTAMP,
             CLOSED_RESULT     VARCHAR(16),
             SAVED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
             CONSTRAINT PK_TARC_DEALS_BEFORE_STATEID PRIMARY KEY (DEAL_ID)
         )';
    END
END^

COMMIT^

EXECUTE BLOCK AS
BEGIN
    /* toate starile ne-implicite, din toti anii; documentele deja arhivate raman neatinse */
    INSERT INTO TARC_DOCS_STATES (DOCID, DOCTYPEID, STATEID, TITLE)
    SELECT d.DOCID, d.DOCTYPEID, d.STATEID, s.TITLE
    FROM TDB_DOCS d
    LEFT JOIN TS_DOCTYPES_STATES s ON s.STATEID = d.STATEID
    WHERE d.STATEID IS NOT NULL AND d.STATEID <> 8
      AND NOT EXISTS(SELECT 1 FROM TARC_DOCS_STATES a WHERE a.DOCID = d.DOCID);

    INSERT INTO TARC_DEALS_BEFORE_STATEID (DEAL_ID, PIPE_STATE_ID, FIN_STATE_ID, CANCEL_REASON_ID,
                                           CHANNEL_ID, CLOSED_AT, CLOSED_RESULT)
    SELECT d.DEAL_ID, d.PIPE_STATE_ID, d.FIN_STATE_ID, d.CANCEL_REASON_ID, d.CHANNEL_ID,
           d.CLOSED_AT, d.CLOSED_RESULT
    FROM TDB_DEALS d
    WHERE NOT EXISTS(SELECT 1 FROM TARC_DEALS_BEFORE_STATEID a WHERE a.DEAL_ID = d.DEAL_ID);
END^

