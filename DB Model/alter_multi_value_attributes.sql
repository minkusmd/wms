/* ============================================================================
   WMS - Atribute MULTI-VALOARE (ex. note olfactive la parfumuri)

   - TS_ATTRIBUTE.FLG_MULTI       : atributul accepta mai multe valori pe produs
   - TS_GOODS_ATTRIBUTE.ORDERNO   : pozitia valorii in cadrul atributului;
                                    PK devine (GOODSID, ATTRID, ORDERNO).
     Atributele single raman cu ORDERNO = 1 -> logica existenta
     UPDATE OR INSERT ... MATCHING (GOODSID, ATTRID, ORDERNO) functioneaza la fel.

   Re-rulabil. A se rula pe baza SW (dupa new_attributes_system.sql +
   alter_goods_attribute_value_text.sql).
   ============================================================================ */

SET TERM ^ ;

/* FLG_MULTI pe TS_ATTRIBUTE */
EXECUTE BLOCK AS BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATION_FIELDS
                 WHERE RDB$RELATION_NAME = 'TS_ATTRIBUTE'
                   AND RDB$FIELD_NAME = 'FLG_MULTI')) THEN
    EXECUTE STATEMENT 'ALTER TABLE TS_ATTRIBUTE ADD FLG_MULTI SMALLINT DEFAULT 0';
END^

/* ORDERNO pe TS_GOODS_ATTRIBUTE */
EXECUTE BLOCK AS BEGIN
  IF (NOT EXISTS(SELECT 1 FROM RDB$RELATION_FIELDS
                 WHERE RDB$RELATION_NAME = 'TS_GOODS_ATTRIBUTE'
                   AND RDB$FIELD_NAME = 'ORDERNO')) THEN
    EXECUTE STATEMENT 'ALTER TABLE TS_GOODS_ATTRIBUTE ADD ORDERNO SMALLINT DEFAULT 1';
END^

SET TERM ; ^

COMMIT;

UPDATE TS_ATTRIBUTE SET FLG_MULTI = 0 WHERE FLG_MULTI IS NULL;
UPDATE TS_GOODS_ATTRIBUTE SET ORDERNO = 1 WHERE ORDERNO IS NULL;
COMMIT;

/* NOT NULL + PK nou (GOODSID, ATTRID, ORDERNO) */
SET TERM ^ ;

EXECUTE BLOCK AS BEGIN
  IF (EXISTS(SELECT 1 FROM RDB$RELATION_FIELDS
             WHERE RDB$RELATION_NAME = 'TS_GOODS_ATTRIBUTE'
               AND RDB$FIELD_NAME = 'ORDERNO'
               AND COALESCE(RDB$NULL_FLAG, 0) = 0)) THEN
    EXECUTE STATEMENT 'ALTER TABLE TS_GOODS_ATTRIBUTE ALTER COLUMN ORDERNO SET NOT NULL';
END^

/* refacem PK-ul doar daca inca e pe 2 coloane */
EXECUTE BLOCK AS
DECLARE VAR CNT INTEGER;
BEGIN
  SELECT COUNT(*) FROM RDB$INDEX_SEGMENTS s
  JOIN RDB$RELATION_CONSTRAINTS c ON c.RDB$INDEX_NAME = s.RDB$INDEX_NAME
  WHERE c.RDB$CONSTRAINT_NAME = 'PK_TS_GOODS_ATTRIBUTE'
  INTO :CNT;
  IF (CNT = 2) THEN
  BEGIN
    EXECUTE STATEMENT 'ALTER TABLE TS_GOODS_ATTRIBUTE DROP CONSTRAINT PK_TS_GOODS_ATTRIBUTE';
    EXECUTE STATEMENT 'ALTER TABLE TS_GOODS_ATTRIBUTE ADD CONSTRAINT PK_TS_GOODS_ATTRIBUTE PRIMARY KEY (GOODSID, ATTRID, ORDERNO)';
  END
END^

SET TERM ; ^

COMMIT;
