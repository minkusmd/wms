/* Pentru fiecare produs al nostru din categoriile active: pretul nostru si cel mai
   mic pret gasit la concurenti (doar produse asociate, active in ultima scanare). */
CREATE OR ALTER PROCEDURE SP_COMPETITOR_SUMMARY
RETURNS (
  CATID        INTEGER,
  CAT_TITLE    VARCHAR(128),
  GOODSID      INTEGER,
  CODE         VARCHAR(255),
  TITLE        VARCHAR(512),
  OUR_PRICE    NUMERIC(15,2),
  MIN_PRICE    NUMERIC(15,2),
  MIN_SITE     VARCHAR(32),
  DIFF_LEI     NUMERIC(15,2),
  DIFF_PCT     NUMERIC(15,2),
  SITES_CNT    INTEGER)
AS
DECLARE VARIABLE CATALOGID INTEGER;
BEGIN
  FOR SELECT c.CATID, c.CATALOGID, c.TITLE
        FROM TWEB_COMPETITOR_CATEGORIES c
       WHERE c.FLG_ACTIVE = 1
       ORDER BY c.ORDERNO, c.CATID
        INTO :CATID, :CATALOGID, :CAT_TITLE
  DO
  BEGIN
    FOR SELECT g.GOODSID, g.CODE, g.TITLE, g.OUR_PRICE
          FROM SP_COMPETITOR_OUR_GOODS(:CATALOGID) g
          INTO :GOODSID, :CODE, :TITLE, :OUR_PRICE
    DO
    BEGIN
      MIN_PRICE = NULL; MIN_SITE = NULL; SITES_CNT = 0; DIFF_LEI = NULL; DIFF_PCT = NULL;
      SELECT MIN(i.PRICE), COUNT(DISTINCT i.SITEID)
        FROM TWEB_COMPETITOR_ITEMS i
       WHERE i.GOODSID = :GOODSID AND i.MATCH_TYPE IN (1, 2) AND i.FLG_ACTIVE = 1
         AND i.PRICE > 0
        INTO :MIN_PRICE, :SITES_CNT;
      IF (MIN_PRICE IS NOT NULL) THEN
      BEGIN
        SELECT FIRST 1 s.SITE_CODE
          FROM TWEB_COMPETITOR_ITEMS i
          JOIN TWEB_COMPETITOR_SITES s ON s.SITEID = i.SITEID
         WHERE i.GOODSID = :GOODSID AND i.MATCH_TYPE IN (1, 2) AND i.FLG_ACTIVE = 1
           AND i.PRICE = :MIN_PRICE
          INTO :MIN_SITE;
        DIFF_LEI = OUR_PRICE - MIN_PRICE;
        IF (MIN_PRICE > 0) THEN DIFF_PCT = ROUND(DIFF_LEI * 100 / MIN_PRICE, 2);
      END
      SUSPEND;
    END
  END
END^

