/* ============================================================================
   Monitorizarea preturilor concurentilor (WMSPriceWatch.exe, dosarul PriceWatch/)

   Programul ruleaza non-stop: parcurge categoriile alese de pe site-urile
   concurentilor (xstore.md, neocomputer.md, geek.md, ...), extrage produsele si
   preturile cu expresii regulate configurate in baza, le asociaza automat cu
   produsele noastre active de pe site (TWEB_CACHE_GOODS, deci FLG_IN_PRICE) si
   pastreaza istoricul preturilor. O data la N ore (implicit 3) scrie un Excel si
   il trimite in Telegram (canalul PRICELISTS = "Online :: Fantastic").

   Tabele:
     TWEB_COMPETITOR_SITES       - site-urile concurentilor + regex-urile de parsare
                                   (un site nou = un rind nou, fara recompilare)
     TWEB_COMPETITOR_CATEGORIES  - categoriile noastre monitorizate (TWEB_CATALOG)
     TWEB_COMPETITOR_CAT_URLS    - URL-ul categoriei pe fiecare site
     TWEB_COMPETITOR_ITEMS       - produsele gasite la concurenti (ultimul pret,
                                   asocierea cu GOODSID-ul nostru)
     TWEB_COMPETITOR_PRICE_HIST  - istoricul schimbarilor de pret
     TWEB_COMPETITOR_SCANS       - jurnalul parcurgerilor (site x categorie)
     TWEB_COMPETITOR_REPORTS     - jurnalul rapoartelor trimise

   Procedura SP_COMPETITOR_OUR_GOODS(CATALOGID) - produsele noastre din categorie
   cu pretul de pe site (PRICE1_LEI din WEB_GET_GOODS_MIN_INFO si reducerea promo).

   Configurare: TS_API_CONFIG, API_CODE = 'COMPETITORS' (vezi sectiunea 7).

   Atentie: domeniul DM_VARCHAR512 are 512 OCTETI (= 128 caractere UTF8), nu 512 caractere -
   de aceea textele lungi (denumiri, URL-uri, erori) folosesc DM_VARCHAR1024 (4096 octeti).
   Sectiunea 9 corecteaza tabelele create de versiunea initiala a scriptului.

   Script RE-RULABIL (20.10.2026). Rollback: competitor_prices_rollback.sql
   ============================================================================ */

