/* Aceeasi selectie ca W_V2_GET_GOODS_LIST_BY_CATALOG2: mapele categoriei
   (TWEB_CATALOG_ITEMS) -> produsele din TWEB_CACHE_GOODS (= active pe site).
   OUR_PRICE = pretul afisat pe site: PRICE1_LEI minus reducerea promo in lei. */
CREATE OR ALTER PROCEDURE SP_COMPETITOR_OUR_GOODS (
  CATALOGID INTEGER)
RETURNS (
  GOODSID      INTEGER,
  CODE         VARCHAR(255),
  TITLE        VARCHAR(512),
  VENDOR       VARCHAR(128),
  PRICE1_LEI   NUMERIC(15,2),
  DISCOUNT_MDL NUMERIC(15,2),
  OUR_PRICE    NUMERIC(15,2))
AS
DECLARE VARIABLE PARENT_LIST VARCHAR(2048);
/* WEB_GET_GOODS_MIN_INFO intoarce CODE VARCHAR(1024), TITLE VARCHAR(2048), VENDOR VARCHAR(1024) */
DECLARE VARIABLE T VARCHAR(2048);
DECLARE VARIABLE C VARCHAR(1024);
DECLARE VARIABLE V VARCHAR(1024);
BEGIN
  SELECT LIST(GOODSPARENTID, ',') FROM TWEB_CATALOG_ITEMS
   WHERE CATALOGID = :CATALOGID AND GET_FLG_VALUE(FLAGS, 1) = 0
    INTO :PARENT_LIST;
  IF (PARENT_LIST IS NULL) THEN EXIT;

  FOR SELECT cg.GOODSID
        FROM TWEB_CACHE_GOODS cg
        JOIN SPLIT(:PARENT_LIST) z ON z.ID = cg.PARENTID
       WHERE cg.GOODSID > 0
        INTO :GOODSID
  DO
  BEGIN
    PRICE1_LEI = NULL; DISCOUNT_MDL = 0; T = NULL; C = NULL; V = NULL;
    SELECT CODE, TITLE, VENDOR, PRICE1_LEI
      FROM WEB_GET_GOODS_MIN_INFO(:GOODSID)
      INTO :C, :T, :V, :PRICE1_LEI;
    SELECT COALESCE(MAX(DISCOUNT_VALUE), 0) FROM W_GET_DISCOUNT_VALUE(:GOODSID) INTO :DISCOUNT_MDL;
    CODE = LEFT(TRIM(COALESCE(C, '')), 255);
    TITLE = LEFT(TRIM(COALESCE(T, '')), 512);
    VENDOR = LEFT(TRIM(COALESCE(V, '')), 128);
    DISCOUNT_MDL = COALESCE(DISCOUNT_MDL, 0);
    OUR_PRICE = COALESCE(PRICE1_LEI, 0) - DISCOUNT_MDL;
    IF (OUR_PRICE < 0) THEN OUR_PRICE = COALESCE(PRICE1_LEI, 0);
    SUSPEND;
  END
END^

