SET TERM ^ ;

EXECUTE BLOCK
AS
BEGIN
  IF (EXISTS (SELECT 1 FROM RDB$PROCEDURES WHERE RDB$PROCEDURE_NAME = 'WEB_NEAREST_HOUSE')) THEN
    EXECUTE STATEMENT 'DROP PROCEDURE WEB_NEAREST_HOUSE';
  IF (EXISTS (SELECT 1 FROM RDB$PROCEDURES WHERE RDB$PROCEDURE_NAME = 'SP_STREET_SECTOR')) THEN
    EXECUTE STATEMENT 'DROP PROCEDURE SP_STREET_SECTOR';
  IF (EXISTS (SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'VW_TS_STREETS')) THEN
    EXECUTE STATEMENT 'DROP VIEW VW_TS_STREETS';
  IF (EXISTS (SELECT 1 FROM RDB$TRIGGERS WHERE RDB$TRIGGER_NAME = 'TRG_TS_STREET_HOUSES_BI')) THEN
    EXECUTE STATEMENT 'DROP TRIGGER TRG_TS_STREET_HOUSES_BI';
  IF (EXISTS (SELECT 1 FROM RDB$TRIGGERS WHERE RDB$TRIGGER_NAME = 'TRG_TS_STREETS_BI')) THEN
    EXECUTE STATEMENT 'DROP TRIGGER TRG_TS_STREETS_BI';
  IF (EXISTS (SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'TS_STREET_HOUSES')) THEN
    EXECUTE STATEMENT 'DROP TABLE TS_STREET_HOUSES';
  IF (EXISTS (SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'TS_STREET_SECTORS')) THEN
    EXECUTE STATEMENT 'DROP TABLE TS_STREET_SECTORS';
  IF (EXISTS (SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'TS_STREETS')) THEN
    EXECUTE STATEMENT 'DROP TABLE TS_STREETS';
  IF (EXISTS (SELECT 1 FROM RDB$GENERATORS WHERE RDB$GENERATOR_NAME = 'SQ_TS_STREETS')) THEN
    EXECUTE STATEMENT 'DROP SEQUENCE SQ_TS_STREETS';
END^

SET TERM ; ^

COMMIT;
