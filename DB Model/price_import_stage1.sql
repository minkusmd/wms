/* --- 3. Statistici rapide pentru WMS / isql ------------------------------- */
CREATE OR ALTER VIEW VW_TPI_RUN (
  RUNID, SUPPLIERID, SUPPLIER_NAME, TRIGGER_KIND, RUN_SLOT, STATUS, STAGE, FLG_DRY_RUN,
  STARTED_AT, FINISHED_AT, DURATION_SEC, PLID, N_VALID, N_NEW, N_RETURNED, N_GONE,
  N_PRICE_UP, N_PRICE_DOWN, N_QUARANTINE, N_APPLIED, ERROR_TEXT)
AS
SELECT r.RUNID, r.SUPPLIERID, c.NAME, r.TRIGGER_KIND, r.RUN_SLOT, r.STATUS, r.STAGE, r.FLG_DRY_RUN,
       r.STARTED_AT, r.FINISHED_AT, DATEDIFF(SECOND FROM r.STARTED_AT TO r.FINISHED_AT), r.PLID,
       r.N_VALID, r.N_NEW, r.N_RETURNED, r.N_GONE, r.N_PRICE_UP, r.N_PRICE_DOWN, r.N_QUARANTINE,
       r.N_APPLIED, r.ERROR_TEXT
FROM TPI_RUN r
LEFT JOIN TS_CUSTOMER c ON c.CUSTOMERID = r.SUPPLIERID;
COMMIT;

/* --- 4. Canalul Telegram (inactiv pina se completeaza CHAT_ID din WMS) ----- */
MERGE INTO TELEGRAM_CHANNELS t
USING (SELECT 'PRICELIST_IMPORT' AS CHANNEL_CODE FROM RDB$DATABASE) s
ON t.CHANNEL_CODE = s.CHANNEL_CODE
WHEN NOT MATCHED THEN
  INSERT (CHANNEL_CODE, TITLE, CHAT_ID, FLG_SILENT, FLG_ACTIVE, NOTE)
  VALUES ('PRICELIST_IMPORT', 'Import automat pricelisturi (PriceImport)', NULL, 0, 0,
          'Se activeaza dupa ce se pune CHAT_ID-ul canalului separat pentru pricelisturi');
COMMIT;

