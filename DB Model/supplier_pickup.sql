/* --- 4. Triggere --------------------------------------------------------- */
CREATE OR ALTER TRIGGER TRG_TS_SUPPLIER_ORDER_RULE_BIU FOR TS_SUPPLIER_ORDER_RULE
ACTIVE BEFORE INSERT OR UPDATE POSITION 0
AS
BEGIN
    IF (INSERTING AND NEW.RULEID IS NULL) THEN
        NEW.RULEID = NEXT VALUE FOR SQ_TS_SUPPLIER_ORDER_RULE_ID;
    IF (NEW.STOCK_SUPPLIERID = NEW.ORDER_SUPPLIERID) THEN
        EXCEPTION ERR_GENERAL_ERROR 'Furnizorul intermediar trebuie sa fie diferit de furnizorul cu stoc';
    NEW.UPDATED_AT = CURRENT_TIMESTAMP;
    IF (NEW.UPDATED_BY IS NULL) THEN
        NEW.UPDATED_BY = CURRENT_USER;
END^

CREATE OR ALTER TRIGGER TRG_TDB_SUPPLIER_PICKUP_BI FOR TDB_SUPPLIER_PICKUP
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.PICKUPID IS NULL) THEN
        NEW.PICKUPID = NEXT VALUE FOR SQ_TDB_SUPPLIER_PICKUP_ID;
    NEW.CREATED_AT = CURRENT_TIMESTAMP;
    IF (NEW.CREATED_BY IS NULL) THEN
        NEW.CREATED_BY = CAST(RDB$GET_CONTEXT('USER_SESSION', 'UserID') AS INTEGER);
    IF (NEW.ORDER_SUPPLIERID IS NULL) THEN
        NEW.ORDER_SUPPLIERID = NEW.STOCK_SUPPLIERID;
    IF (NEW.PICKUP_SUPPLIERID IS NULL) THEN
        NEW.PICKUP_SUPPLIERID = NEW.STOCK_SUPPLIERID;
    IF (NEW.STATEID = 0 AND NEW.DRIVERID IS NOT NULL) THEN
        NEW.STATEID = 1;
END^

CREATE OR ALTER TRIGGER TRG_TDB_SUPPLIER_PICKUP_BU FOR TDB_SUPPLIER_PICKUP
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
    NEW.UPDATED_AT = CURRENT_TIMESTAMP;
    IF (NEW.UPDATED_BY IS NULL OR NEW.UPDATED_BY IS NOT DISTINCT FROM OLD.UPDATED_BY) THEN
        NEW.UPDATED_BY = CAST(RDB$GET_CONTEXT('USER_SESSION', 'UserID') AS INTEGER);

    /* atribuirea soferului muta sarcina noua in "atribuita"; scoaterea lui o intoarce */
    IF (NEW.STATEID = 0 AND NEW.DRIVERID IS NOT NULL) THEN
        NEW.STATEID = 1;
    IF (NEW.STATEID = 1 AND NEW.DRIVERID IS NULL) THEN
        NEW.STATEID = 0;

    IF (NEW.STATEID = 2 AND OLD.STATEID <> 2) THEN
        NEW.PICKED_AT = CURRENT_TIMESTAMP;
    IF (NEW.STATEID <> 2) THEN
        NEW.PICKED_AT = NULL;
END^

/* --- 5. Vederea pentru grila -------------------------------------------- */
CREATE OR ALTER VIEW VW_TDB_SUPPLIER_PICKUP (
    PICKUPID, DOCID, DTDEP, DOC_DATA, CLIENTID, CLIENT_NAME,
    GOODSID, GOODS_TITLE, GOODS_CODE, QTY,
    STOCK_SUPPLIERID, STOCK_SUPPLIER_NAME,
    ORDER_SUPPLIERID, ORDER_SUPPLIER_NAME,
    PICKUP_SUPPLIERID, PICKUP_SUPPLIER_NAME,
    DRIVERID, DRIVER_NAME,
    STATEID, STATE_NAME, PLAN_DATE, PICKED_AT, NOTE,
    CREATED_AT, CREATED_BY, CREATED_BY_NAME, UPDATED_AT
)
AS
SELECT
    P.PICKUPID, P.DOCID, P.DTDEP, D.DATA, D.CT,
    (SELECT C.NAME FROM TS_CUSTOMER C WHERE C.CUSTOMERID = D.CT),
    P.GOODSID,
    (SELECT G.TITLE FROM TS_GOODS G WHERE G.GOODSID = P.GOODSID),
    P.GOODS_CODE, P.QTY,
    P.STOCK_SUPPLIERID,
    (SELECT C.NAME FROM TS_CUSTOMER C WHERE C.CUSTOMERID = P.STOCK_SUPPLIERID),
    P.ORDER_SUPPLIERID,
    (SELECT C.NAME FROM TS_CUSTOMER C WHERE C.CUSTOMERID = P.ORDER_SUPPLIERID),
    P.PICKUP_SUPPLIERID,
    (SELECT C.NAME FROM TS_CUSTOMER C WHERE C.CUSTOMERID = P.PICKUP_SUPPLIERID),
    P.DRIVERID,
    (SELECT C.NAME FROM TS_CUSTOMER C WHERE C.CUSTOMERID = P.DRIVERID),
    P.STATEID,
    CASE P.STATEID
        WHEN 0 THEN 'Noua'
        WHEN 1 THEN 'Atribuita'
        WHEN 2 THEN 'Ridicata'
        WHEN 3 THEN 'Anulata'
    END,
    P.PLAN_DATE, P.PICKED_AT, P.NOTE,
    P.CREATED_AT, P.CREATED_BY,
    (SELECT U.FULL_NAME FROM TS_USERS U WHERE U.USERID = P.CREATED_BY),
    P.UPDATED_AT
FROM TDB_SUPPLIER_PICKUP P
LEFT JOIN TDB_DOCS D ON D.DOCID = P.DOCID^

