/* ============================================================================
   Ridicari de marfa de la furnizori (modulul soferilor) - iteratia 1

   Flux: in comanda clientului (frame10NakladnieRN, butonul "Alege furnizorul")
   operatorul alege furnizorul la care vede stocul, apoi confirma:
     - furnizorul prin care se plaseaza comanda (intermediar; implicit din
       regula TS_SUPPLIER_ORDER_RULE, se poate schimba),
     - de unde ridica soferul marfa (la sursa sau la intermediar),
     - cantitatea (1 .. QTY din comanda minus ce e deja planificat).
   Rezultatul = un rand in TDB_SUPPLIER_PICKUP. In lista "Ridicari de la
   furnizori" se atribuie soferul si se marcheaza ridicarea.

   TS_SUPPLIER_ORDER_RULE  - o regula per furnizor sursa:
       STOCK_SUPPLIERID -> ORDER_SUPPLIERID, PICKUP_FROM (0 = sursa, 1 = intermediar)
       Ex.: Ultra (202294) -> Furnizor-Prim, ridicare de la ...
   TDB_SUPPLIER_PICKUP     - sarcinile de ridicare.
       STATEID: 0 = noua, 1 = atribuita soferului, 2 = ridicata, 3 = anulata
   VW_TDB_SUPPLIER_PICKUP  - vedere read-only cu denumirile, pentru grila.

   Script RE-RULABIL: se poate executa de mai multe ori fara efecte adverse.
   ============================================================================ */

SET TERM ^ ;

/* --- 1. Tabele ----------------------------------------------------------- */
EXECUTE BLOCK AS
BEGIN
    IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS
                   WHERE TRIM(RDB$RELATION_NAME) = 'TS_SUPPLIER_ORDER_RULE')) THEN
        EXECUTE STATEMENT
        'CREATE TABLE TS_SUPPLIER_ORDER_RULE (
             RULEID           INTEGER NOT NULL,
             STOCK_SUPPLIERID INTEGER NOT NULL,
             ORDER_SUPPLIERID INTEGER NOT NULL,
             PICKUP_FROM      SMALLINT DEFAULT 0 NOT NULL,
             FLG_ACTIVE       SMALLINT DEFAULT 1 NOT NULL,
             NOTE             VARCHAR(256),
             UPDATED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
             UPDATED_BY       VARCHAR(64),
             CONSTRAINT PK_TS_SUPPLIER_ORDER_RULE PRIMARY KEY (RULEID),
             CONSTRAINT CHK_TS_SUPPLIER_ORDER_RULE_PF CHECK (PICKUP_FROM IN (0, 1))
         )';

    IF (NOT EXISTS(SELECT 1 FROM RDB$RELATIONS
                   WHERE TRIM(RDB$RELATION_NAME) = 'TDB_SUPPLIER_PICKUP')) THEN
        EXECUTE STATEMENT
        'CREATE TABLE TDB_SUPPLIER_PICKUP (
             PICKUPID          INTEGER NOT NULL,
             DOCID             INTEGER NOT NULL,
             DTDEP             INTEGER,
             GOODSID           INTEGER NOT NULL,
             GOODS_CODE        VARCHAR(128),
             QTY               DOUBLE PRECISION NOT NULL,
             STOCK_SUPPLIERID  INTEGER NOT NULL,
             ORDER_SUPPLIERID  INTEGER NOT NULL,
             PICKUP_SUPPLIERID INTEGER NOT NULL,
             DRIVERID          INTEGER,
             STATEID           SMALLINT DEFAULT 0 NOT NULL,
             PLAN_DATE         DATE,
             PICKED_AT         TIMESTAMP,
             NOTE              VARCHAR(512),
             CREATED_AT        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
             CREATED_BY        INTEGER,
             UPDATED_AT        TIMESTAMP,
             UPDATED_BY        INTEGER,
             CONSTRAINT PK_TDB_SUPPLIER_PICKUP PRIMARY KEY (PICKUPID),
             CONSTRAINT CHK_TDB_SUPPLIER_PICKUP_QTY CHECK (QTY > 0),
             CONSTRAINT CHK_TDB_SUPPLIER_PICKUP_STATE CHECK (STATEID IN (0, 1, 2, 3))
         )';
END^

COMMIT WORK^

