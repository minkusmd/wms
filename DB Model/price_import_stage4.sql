/* --- SP_PI_LINK_GOODS -------------------------------------------------------
   RESULT: LINKED (rind nou), ALREADY (codul e deja legat la furnizor - de orice produs),
           NO_GOODS (produs inexistent / mapa), NO_SUPPLIER (furnizorul nu e in TPI_SUPPLIER). */
SET TERM ^ ;
CREATE OR ALTER PROCEDURE SP_PI_LINK_GOODS (
  P_SUPPLIERID INTEGER,
  P_CODE       VARCHAR(128),
  P_GOODSID    INTEGER,
  P_TITLE      VARCHAR(1024),
  P_USERID     INTEGER)
RETURNS (
  RESULT VARCHAR(16))
SQL SECURITY DEFINER
AS
BEGIN
  IF (NOT EXISTS (SELECT 1 FROM TPI_SUPPLIER s WHERE s.SUPPLIERID = :P_SUPPLIERID)) THEN
  BEGIN
    RESULT = 'NO_SUPPLIER';
    EXIT;
  END
  IF (NOT EXISTS (SELECT 1 FROM TS_GOODS g WHERE g.GOODSID = :P_GOODSID AND COALESCE(g.FLG_FOLDER, 0) = 0)) THEN
  BEGIN
    RESULT = 'NO_GOODS';
    EXIT;
  END
  IF (EXISTS (SELECT 1 FROM TS_GOODS_FOREIGN gf WHERE gf.CUSTOMERID = :P_SUPPLIERID AND gf.GOODS_CODE = :P_CODE)) THEN
  BEGIN
    RESULT = 'ALREADY';
    EXIT;
  END
  IF (COALESCE(P_USERID, 0) > 0) THEN
    RDB$SET_CONTEXT('USER_SESSION', 'UserID', :P_USERID);
  INSERT INTO TS_GOODS_FOREIGN (GOODSID, CUSTOMERID, GOODS_CODE, GOODS_TITLE, PRICE4, PRICE7, FLAGS)
  VALUES (:P_GOODSID, :P_SUPPLIERID, :P_CODE, LEFT(COALESCE(NULLIF(TRIM(:P_TITLE), ''), :P_CODE), 1024), 0, 0, 0);
  RESULT = 'LINKED';
END^
SET TERM ; ^
COMMIT;
