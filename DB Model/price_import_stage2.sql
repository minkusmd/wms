/* --- SP_PI_APPLY_KIND -------------------------------------------------------
   Un document 1414 din randurile lotului P_BATCHID cu KIND = P_KIND. Intoarce DOCID = 0 daca nu
   are randuri. Randurile respinse la inchidere primesc FLG_REJECTED = 1 si mesajul erorii.
   Ultimul pas (FLAGS bit 10 pe document) il face CLOSE_REEVALUARE.
   Procedura executabila: EXECUTE PROCEDURE SP_PI_APPLY_KIND(lot, tip) RETURNING_VALUES ... */
SET TERM ^ ;
CREATE OR ALTER PROCEDURE SP_PI_APPLY_KIND (
  P_BATCHID BIGINT,
  P_KIND    SMALLINT)
RETURNS (
  DOCID      INTEGER,
  N_ROWS     INTEGER,
  N_REJECTED INTEGER)
SQL SECURITY DEFINER
AS
DECLARE VARIABLE V_SUPPLIERID INTEGER;
DECLARE VARIABLE V_FIRMAID INTEGER;
DECLARE VARIABLE V_USERID INTEGER;
DECLARE VARIABLE V_DISCOUNT NUMERIC(6,3);
DECLARE VARIABLE V_STATUS VARCHAR(12);
DECLARE VARIABLE V_IN_PRICE SMALLINT;
DECLARE VARIABLE V_CLOSED SMALLINT;
DECLARE VARIABLE V_MSG VARCHAR(1024);
DECLARE VARIABLE V_CODE VARCHAR(128);
DECLARE VARIABLE V_POS INTEGER;
DECLARE VARIABLE V_DELETED INTEGER;
BEGIN
  DOCID = 0;
  N_ROWS = 0;
  N_REJECTED = 0;

  SELECT b.SUPPLIERID, b.FIRMAID, b.USERID, b.RRP_DISCOUNT, b.STATUS
  FROM TPI_APPLY_BATCH b
  WHERE b.BATCHID = :P_BATCHID
  INTO :V_SUPPLIERID, :V_FIRMAID, :V_USERID, :V_DISCOUNT, :V_STATUS;
  IF (V_SUPPLIERID IS NULL) THEN
    EXCEPTION ERR_GENERAL_ERROR 'SP_PI_APPLY_KIND: lotul ' || :P_BATCHID || ' nu exista';
  IF (V_STATUS <> 'PREPARED') THEN
    EXCEPTION ERR_GENERAL_ERROR 'SP_PI_APPLY_KIND: lotul ' || :P_BATCHID || ' are statusul ' || :V_STATUS;
  IF (COALESCE(V_USERID, 0) <= 0 OR COALESCE(V_FIRMAID, 0) <= 0) THEN
    EXCEPTION ERR_GENERAL_ERROR 'SP_PI_APPLY_KIND: lotul ' || :P_BATCHID || ' nu are firma / utilizator';

  SELECT COUNT(*) FROM TPI_APPLY_ROW r WHERE r.BATCHID = :P_BATCHID AND r.KIND = :P_KIND INTO :N_ROWS;
  IF (N_ROWS = 0) THEN
    EXIT;

  /* contextul sesiunii, ca in WMS: firma documentului si utilizatorul (triggere, CREATED_BY) */
  EXECUTE PROCEDURE PROC_USER_SET_DT(:V_FIRMAID);
  RDB$SET_CONTEXT('USER_SESSION', 'UserID', :V_USERID);

  /* acelasi apel ca Tframe78PriceList.AddDocumentReeveluare / PriceListReevaluationUnit */
  SELECT NEWDOCID FROM SP_CREATE_NEW_DOCUMENT(:V_FIRMAID, :V_SUPPLIERID, -1, -1, -1, -1, 0, 0, 498, 0, 1, 1, -1, 0,
                                             1414, 0, -1, -1)
  INTO :DOCID;
  IF (COALESCE(DOCID, 0) <= 0) THEN
    EXCEPTION ERR_GENERAL_ERROR 'SP_PI_APPLY_KIND: reevaluarea nu a putut fi creata';

  V_IN_PRICE = IIF(P_KIND = 1, 0, 1);

  /* cu pret indicativ (AddRecordToReevaluare) si fara (AddRecordToReevaluareVinzare); BARCODE = '' ca in WMS */
  INSERT INTO TDB_GOODS_PRICE (DOCID, GOODSID, SUPPLIER_GOODS_CODE, PRICE0, PRICE3, CURRENCYID, CURRENCY3ID,
                               PRICE7, CURRENCY7ID, BARCODE, FLAGS)
  SELECT :DOCID, r.GOODSID, r.SUPPLIER_GOODS_CODE, r.PRICE0, r.PRICE3, r.CURRENCY0ID, r.CURRENCY3ID,
         r.PRICE7, r.CURRENCY7ID, '', SET_FLG_VALUE(SET_FLG_VALUE(0, 3, :V_IN_PRICE), 4, r.FLG_EPP)
  FROM TPI_APPLY_ROW r
  WHERE r.BATCHID = :P_BATCHID AND r.KIND = :P_KIND AND r.PRICE7 > 0;

  INSERT INTO TDB_GOODS_PRICE (DOCID, GOODSID, SUPPLIER_GOODS_CODE, PRICE0, PRICE3, CURRENCYID, CURRENCY3ID,
                               BARCODE, FLAGS)
  SELECT :DOCID, r.GOODSID, r.SUPPLIER_GOODS_CODE, r.PRICE0, r.PRICE3, r.CURRENCY0ID, r.CURRENCY3ID,
         '', SET_FLG_VALUE(SET_FLG_VALUE(0, 3, :V_IN_PRICE), 4, r.FLG_EPP)
  FROM TPI_APPLY_ROW r
  WHERE r.BATCHID = :P_BATCHID AND r.KIND = :P_KIND AND NOT (r.PRICE7 > 0);

  UPDATE TPI_APPLY_ROW r SET r.DOCID = :DOCID WHERE r.BATCHID = :P_BATCHID AND r.KIND = :P_KIND;

  /* micsorarea RRP-ului cu procentul furnizorului (ca in WMS); 0 la anularea unei rulari */
  IF (COALESCE(V_DISCOUNT, 0) <> 0) THEN
    EXECUTE PROCEDURE ADJUST_RRP_REEVALUATION(:DOCID, :V_DISCOUNT);

  /* CLOSE_REEVALUARE; produsul raportat ca "goodscode: <cod> [..." se scoate din document si se reia.
     Blocul cu WHEN anuleaza (savepoint) tot ce a facut inchiderea esuata. */
  V_CLOSED = 0;
  WHILE (V_CLOSED = 0) DO
  BEGIN
    BEGIN
      EXECUTE PROCEDURE CLOSE_REEVALUARE(:DOCID);
      V_CLOSED = 1;
    WHEN ANY DO
    BEGIN
      V_MSG = LEFT(COALESCE(RDB$ERROR(MESSAGE), ''), 1024);
      V_POS = POSITION('goodscode: ' IN V_MSG);
      IF (V_POS = 0 OR N_REJECTED >= 50) THEN
        EXCEPTION;
      V_CODE = SUBSTRING(V_MSG FROM V_POS + 11);
      V_POS = POSITION('[' IN V_CODE);
      IF (V_POS > 0) THEN
        V_CODE = LEFT(V_CODE, V_POS - 1);
      V_CODE = TRIM(V_CODE);
      DELETE FROM TDB_GOODS_PRICE g WHERE g.DOCID = :DOCID AND g.SUPPLIER_GOODS_CODE = :V_CODE;
      V_DELETED = ROW_COUNT;
      IF (V_DELETED = 0) THEN
        EXCEPTION;
      N_REJECTED = N_REJECTED + 1;
      UPDATE TPI_APPLY_ROW r SET r.FLG_REJECTED = 1, r.REJECT_MSG = :V_MSG
      WHERE r.BATCHID = :P_BATCHID AND r.KIND = :P_KIND AND r.SUPPLIER_GOODS_CODE = :V_CODE;
    END
    END
  END
END^
SET TERM ; ^
COMMIT;

/* --- SP_PI_WATCHDOG ---------------------------------------------------------
   De programat in SWNService (la 15 minute). Alerte in ERRORS, deduplicate prin TPI_ALERT_STATE:
     - pi-worker a trimis heartbeat, dar nu de P_HEARTBEAT_MIN minute -> serviciul e oprit;
     - la P_WINDOW_GRACE_MIN minute dupa startul unei ferestre (09:00 / 15:00) nu exista nicio rulare
       SCHEDULE pentru ea -> fereastra nu a rulat deloc.
   O alerta se repeta cel mult o data la P_REPEAT_MIN minute; la revenire se trimite "rezolvat". */
SET TERM ^ ;
CREATE OR ALTER PROCEDURE SP_PI_WATCHDOG (
  P_HEARTBEAT_MIN    INTEGER = 5,
  P_WINDOW_GRACE_MIN INTEGER = 75,
  P_REPEAT_MIN       INTEGER = 360)
RETURNS (
  ALERTS INTEGER)
SQL SECURITY DEFINER
AS
DECLARE VARIABLE V_HB TIMESTAMP;
DECLARE VARIABLE V_PROBLEM SMALLINT;
DECLARE VARIABLE V_KEY VARCHAR(128);
DECLARE VARIABLE V_TEXT VARCHAR(1024);
DECLARE VARIABLE V_LAST_SENT TIMESTAMP;
DECLARE VARIABLE V_RESOLVED TIMESTAMP;
DECLARE VARIABLE V_EXISTS SMALLINT;
BEGIN
  ALERTS = 0;

  FOR SELECT K, PROBLEM, TXT FROM (
    /* 1. heartbeat */
    SELECT 'WATCHDOG|HEARTBEAT' AS K,
           IIF(h.HEARTBEAT_AT < DATEADD(-:P_HEARTBEAT_MIN MINUTE TO CURRENT_TIMESTAMP), 1, 0) AS PROBLEM,
           'PriceImport: serviciul pi-worker nu mai raspunde (ultimul heartbeat ' ||
             SUBSTRING(CAST(h.HEARTBEAT_AT AS VARCHAR(24)) FROM 1 FOR 16) || ', ' || TRIM(COALESCE(h.HOST, '')) || ')' AS TXT
    FROM TPI_HEARTBEAT h WHERE h.INSTANCE = 'pi-worker'
    UNION ALL
    /* 2. ferestrele de azi trecute de termen */
    SELECT 'WATCHDOG|WINDOW|' || w.SLOT,
           IIF(EXISTS (SELECT 1 FROM TPI_RUN r WHERE r.TRIGGER_KIND = 'SCHEDULE' AND r.RUN_SLOT = w.SLOT), 0, 1),
           'PriceImport: fereastra ' || w.SLOT || ':00 nu a rulat deloc (nicio rulare programata)'
    FROM (SELECT CAST(CURRENT_DATE AS VARCHAR(10)) || ' 09' AS SLOT, 9 AS H FROM RDB$DATABASE
          UNION ALL
          SELECT CAST(CURRENT_DATE AS VARCHAR(10)) || ' 15', 15 FROM RDB$DATABASE) w
    WHERE CURRENT_TIMESTAMP > DATEADD(:P_WINDOW_GRACE_MIN MINUTE TO DATEADD(w.H HOUR TO CAST(CURRENT_DATE AS TIMESTAMP)))
      AND EXISTS (SELECT 1 FROM TPI_HEARTBEAT h2 WHERE h2.INSTANCE = 'pi-worker')
      AND EXISTS (SELECT 1 FROM TPI_SUPPLIER s WHERE s.FLG_ACTIVE = 1)
  ) INTO :V_KEY, :V_PROBLEM, :V_TEXT
  DO
  BEGIN
    V_EXISTS = 0;
    V_LAST_SENT = NULL;
    V_RESOLVED = NULL;
    SELECT 1, a.LAST_SENT_AT, a.RESOLVED_AT FROM TPI_ALERT_STATE a WHERE a.ALERT_KEY = :V_KEY
    INTO :V_EXISTS, :V_LAST_SENT, :V_RESOLVED;

    IF (V_PROBLEM = 1) THEN
    BEGIN
      IF (V_EXISTS = 0) THEN
        INSERT INTO TPI_ALERT_STATE (ALERT_KEY, SEVERITY, FIRST_SEEN, LAST_SEEN, OCCURRENCES, LAST_MESSAGE)
        VALUES (:V_KEY, 'CRIT', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 1, :V_TEXT);
      ELSE IF (V_RESOLVED IS NOT NULL) THEN
      BEGIN
        UPDATE TPI_ALERT_STATE SET FIRST_SEEN = CURRENT_TIMESTAMP, LAST_SEEN = CURRENT_TIMESTAMP, OCCURRENCES = 1,
          RESOLVED_AT = NULL, LAST_SENT_AT = NULL, LAST_MESSAGE = :V_TEXT WHERE ALERT_KEY = :V_KEY;
        V_LAST_SENT = NULL;
      END
      ELSE
        UPDATE TPI_ALERT_STATE SET LAST_SEEN = CURRENT_TIMESTAMP, OCCURRENCES = OCCURRENCES + 1,
          LAST_MESSAGE = :V_TEXT WHERE ALERT_KEY = :V_KEY;

      IF (V_LAST_SENT IS NULL OR V_LAST_SENT < DATEADD(-:P_REPEAT_MIN MINUTE TO CURRENT_TIMESTAMP)) THEN
      BEGIN
        IF (NOT EXISTS (SELECT 1 FROM TPI_ALERT_STATE a WHERE a.ALERT_KEY = :V_KEY
                        AND a.MUTED_UNTIL > CURRENT_TIMESTAMP)) THEN
        BEGIN
          EXECUTE PROCEDURE SP_TELEGRAM_SEND('ERRORS', :V_TEXT, NULL, -50, NULL, 1);
          ALERTS = ALERTS + 1;
        END
        UPDATE TPI_ALERT_STATE SET LAST_SENT_AT = CURRENT_TIMESTAMP WHERE ALERT_KEY = :V_KEY;
      END
    END
    ELSE IF (V_EXISTS = 1 AND V_RESOLVED IS NULL) THEN
    BEGIN
      UPDATE TPI_ALERT_STATE SET RESOLVED_AT = CURRENT_TIMESTAMP WHERE ALERT_KEY = :V_KEY;
      IF (V_LAST_SENT IS NOT NULL) THEN
      BEGIN
        EXECUTE PROCEDURE SP_TELEGRAM_SEND('ERRORS', 'PriceImport: rezolvat - ' || :V_KEY, NULL, -50, NULL, 0);
        ALERTS = ALERTS + 1;
      END
    END
  END
END^
SET TERM ; ^
COMMIT;
