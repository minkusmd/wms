/* --- SP_PI_CONTENT_TRANSFER -------------------------------------------------
   GOODSID null = codul nu e legat de un produs real. IMAGES = imagini copiate, DESCRIPTIONS = 1 daca
   descrierea s-a scris / completat. Codurile se trimit in ordine alfabetica: la un produs legat de
   mai multe coduri ale furnizorului imaginile vin de la primul cod care le are (ca in Delphi). */
SET TERM ^ ;
CREATE OR ALTER PROCEDURE SP_PI_CONTENT_TRANSFER (
  P_SUPPLIERID INTEGER,
  P_CODE       VARCHAR(128),
  P_USERID     INTEGER)
RETURNS (
  GOODSID      INTEGER,
  IMAGES       INTEGER,
  DESCRIPTIONS INTEGER)
SQL SECURITY DEFINER
AS
  DECLARE IMG BLOB SUB_TYPE BINARY;
BEGIN
  IMAGES = 0;
  DESCRIPTIONS = 0;
  SELECT MIN(f.GOODSID) FROM TS_GOODS_FOREIGN f
    JOIN TS_GOODS g ON g.GOODSID = f.GOODSID AND COALESCE(g.FLG_FOLDER, 0) = 0
   WHERE f.CUSTOMERID = :P_SUPPLIERID AND f.GOODS_CODE = :P_CODE
    INTO :GOODSID;
  IF (GOODSID IS NULL) THEN
    EXIT;
  IF (COALESCE(P_USERID, 0) > 0) THEN
    RDB$SET_CONTEXT('USER_SESSION', 'UserID', :P_USERID);

  /* imaginile - doar la produsul fara nicio imagine; ORDERNO / IMAGE_HASH le pune TRG_TS_GOODS_IMAGE_BI0 */
  IF (NOT EXISTS (SELECT 1 FROM TS_GOODS_IMAGE x WHERE x.GOODSID = :GOODSID)) THEN
    FOR SELECT pi.IMAGE FROM TS_PRICELIST_ITEMS_IMAGES pi
         WHERE pi.SUPPLIERID = :P_SUPPLIERID AND pi.SUPPLIER_GOODS_CODE = :P_CODE AND pi.IMAGE IS NOT NULL
           AND NOT EXISTS (SELECT 1 FROM TS_PRICELIST_ITEMS_IMAGES p2
                            WHERE p2.SUPPLIERID = pi.SUPPLIERID AND p2.SUPPLIER_GOODS_CODE = pi.SUPPLIER_GOODS_CODE
                              AND p2.IMAGE IS NOT NULL AND COALESCE(p2.ORDERNO, 0) < COALESCE(pi.ORDERNO, 0)
                              AND HASH(p2.IMAGE) = HASH(pi.IMAGE))
         ORDER BY pi.ORDERNO
          INTO :IMG
    DO
    BEGIN
      INSERT INTO TS_GOODS_IMAGE (GOODSID, IMAGE) VALUES (:GOODSID, :IMG);
      IMAGES = IMAGES + 1;
    END

  /* descrierea - rind nou sau completarea limbii goale */
  MERGE INTO TS_GOODS_DSC d
  USING (SELECT CAST(:GOODSID AS INTEGER) AS GID,
                IIF(CHAR_LENGTH(TRIM(pd.DESCRIPTION_RO)) >= 20, pd.DESCRIPTION_RO, NULL) AS RO,
                IIF(CHAR_LENGTH(TRIM(pd.DESCRIPTION_RU)) >= 20, pd.DESCRIPTION_RU, NULL) AS RU
           FROM TS_PRICELIST_ITEMS_DESCRIPTION pd
          WHERE pd.SUPPLIERID = :P_SUPPLIERID AND pd.SUPPLIER_GOODS_CODE = :P_CODE) s
  ON d.GOODSID = s.GID
  WHEN MATCHED AND ((COALESCE(CHAR_LENGTH(TRIM(d.DESCRIPTION_RO)), 0) < 20 AND s.RO IS NOT NULL)
                 OR (COALESCE(CHAR_LENGTH(TRIM(d.DESCRIPTION)), 0) < 20 AND s.RU IS NOT NULL)) THEN
    UPDATE SET
      DESCRIPTION_RO = IIF(COALESCE(CHAR_LENGTH(TRIM(d.DESCRIPTION_RO)), 0) < 20,
                           COALESCE(s.RO, d.DESCRIPTION_RO), d.DESCRIPTION_RO),
      DESCRIPTION = IIF(COALESCE(CHAR_LENGTH(TRIM(d.DESCRIPTION)), 0) < 20,
                        COALESCE(s.RU, d.DESCRIPTION), d.DESCRIPTION)
  WHEN NOT MATCHED AND (s.RO IS NOT NULL OR s.RU IS NOT NULL) THEN
    INSERT (GOODSID, DESCRIPTION_RO, DESCRIPTION) VALUES (s.GID, s.RO, s.RU);
  DESCRIPTIONS = ROW_COUNT;
END^
SET TERM ; ^
COMMIT;
