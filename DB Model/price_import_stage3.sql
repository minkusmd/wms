/* ============================================================================
   PriceImport - etapa 3: furnizorii manuali (Excel / CSV de pe Viber) prin botul Telegram pi-bot
   Plan: Documents/plan-import-automat-pricelisturi-2026-10-27.md (sectiunea 6)
   Cere price_import_stage1.sql + price_import_stage2.sql rulate inainte.

   Obiecte:
     TPI_BOT_USER    - cine poate vorbi cu botul (ID-ul Telegram) si ce poate: VIEW (raport, previzualizare)
                       sau APPLY (si aplica preturile / decide carantina)
     TPI_INBOX_FILE  - fisierele primite: hash, expeditor, furnizor recunoscut, status, rularea
     TPI_FILE_RULE   - regulile de recunoastere a furnizorului unui fisier (expeditor, nume de fisier,
                       text, semnatura antetului), invatate si din alegerile facute in bot
     TPI_BOT_STATE   - starea botului (offset-ul getUpdates), ca repornirea sa nu reia mesajele

   Furnizorii manuali se adauga in TPI_SUPPLIER cu ADAPTER_CODE = 'excel', SOURCE_KIND = 'B',
   WINDOW_MASK = 0 (nu se descarca in ferestre) + maparea coloanelor in PriceImport/suppliers/<id>.yaml.

   Script RE-RULABIL (28.10.2026). Rollback: price_import_stage3_rollback.sql
   ============================================================================ */

SET TERM ^ ;

EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS (SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'TPI_BOT_USER')) THEN
    EXECUTE STATEMENT
      'CREATE TABLE TPI_BOT_USER (
         TG_USER_ID   BIGINT       NOT NULL,
         NAME         VARCHAR(128) NOT NULL,
         ROLE_CODE    VARCHAR(8)   DEFAULT ''VIEW'' NOT NULL,
         FLG_ACTIVE   SMALLINT     DEFAULT 1 NOT NULL,
         NOTE         VARCHAR(512),
         CREATED_AT   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
         CONSTRAINT PK_TPI_BOT_USER PRIMARY KEY (TG_USER_ID),
         CONSTRAINT CK_TPI_BOT_USER_ROLE CHECK (ROLE_CODE IN (''VIEW'', ''APPLY''))
       )';

  IF (NOT EXISTS (SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'TPI_INBOX_FILE')) THEN
    EXECUTE STATEMENT
      'CREATE TABLE TPI_INBOX_FILE (
         FILEID        BIGINT GENERATED BY DEFAULT AS IDENTITY,
         TG_CHAT_ID    BIGINT       NOT NULL,
         TG_MESSAGE_ID BIGINT       NOT NULL,
         TG_FILE_UNIQUE_ID VARCHAR(64) NOT NULL,
         SENDER_TG_ID  BIGINT,
         SENDER_NAME   VARCHAR(256),
         FORWARD_FROM  VARCHAR(256),
         CAPTION       VARCHAR(1024),
         FILE_NAME     VARCHAR(512) NOT NULL,
         FILE_SIZE     INTEGER,
         SHA256        CHAR(64)     NOT NULL,
         STORAGE_PATH  VARCHAR(1024),
         RECEIVED_AT   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
         SUPPLIERID    INTEGER,
         DETECT_METHOD VARCHAR(16),
         DETECT_SCORE  NUMERIC(5,3),
         STATUS        VARCHAR(16)  NOT NULL,
         RUNID         BIGINT,
         DECIDED_BY    VARCHAR(64),
         DECIDED_AT    TIMESTAMP,
         NOTE          VARCHAR(1024),
         CONSTRAINT PK_TPI_INBOX_FILE PRIMARY KEY (FILEID),
         CONSTRAINT UQ_TPI_INBOX_FILE_TG UNIQUE (TG_FILE_UNIQUE_ID),
         CONSTRAINT CK_TPI_INBOX_FILE_ST CHECK (STATUS IN (''RECEIVED'', ''NEEDS_SUPPLIER'', ''PREVIEW'', ''APPLIED'',
           ''REPORTED'', ''REJECTED'', ''DUPLICATE'', ''FAILED''))
       )';

  IF (NOT EXISTS (SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'TPI_FILE_RULE')) THEN
    EXECUTE STATEMENT
      'CREATE TABLE TPI_FILE_RULE (
         RULEID      INTEGER GENERATED BY DEFAULT AS IDENTITY,
         SUPPLIERID  INTEGER       NOT NULL,
         RULE_TYPE   VARCHAR(16)   NOT NULL,
         PATTERN     VARCHAR(1024) NOT NULL,
         WEIGHT      NUMERIC(4,2)  DEFAULT 1 NOT NULL,
         FLG_ACTIVE  SMALLINT      DEFAULT 1 NOT NULL,
         FLG_LEARNED SMALLINT      DEFAULT 0 NOT NULL,
         CREATED_AT  TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
         CONSTRAINT PK_TPI_FILE_RULE PRIMARY KEY (RULEID),
         CONSTRAINT FK_TPI_FILE_RULE_SUPPLIER FOREIGN KEY (SUPPLIERID) REFERENCES TPI_SUPPLIER (SUPPLIERID),
         CONSTRAINT CK_TPI_FILE_RULE_TYPE CHECK (RULE_TYPE IN (''SENDER_TG_ID'', ''FILENAME_RE'', ''CAPTION_RE'',
           ''HEADER_SIG'', ''SHEET_NAME''))
       )';

  IF (NOT EXISTS (SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'TPI_BOT_STATE')) THEN
    EXECUTE STATEMENT
      'CREATE TABLE TPI_BOT_STATE (
         PARAM_NAME  VARCHAR(64)   NOT NULL,
         PARAM_VALUE VARCHAR(1024),
         UPDATED_AT  TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
         CONSTRAINT PK_TPI_BOT_STATE PRIMARY KEY (PARAM_NAME)
       )';
END^

SET TERM ; ^
COMMIT;

SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS (SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'IX_TPI_INBOX_FILE_SHA')) THEN
    EXECUTE STATEMENT 'CREATE INDEX IX_TPI_INBOX_FILE_SHA ON TPI_INBOX_FILE (SHA256)';
  IF (NOT EXISTS (SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'IX_TPI_INBOX_FILE_RUN')) THEN
    EXECUTE STATEMENT 'CREATE INDEX IX_TPI_INBOX_FILE_RUN ON TPI_INBOX_FILE (RUNID)';
  IF (NOT EXISTS (SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'IX_TPI_FILE_RULE_SUPP')) THEN
    EXECUTE STATEMENT 'CREATE INDEX IX_TPI_FILE_RULE_SUPP ON TPI_FILE_RULE (RULE_TYPE, SUPPLIERID)';
END^
SET TERM ; ^
COMMIT;
