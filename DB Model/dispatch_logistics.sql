/* Fotografiile care lipsesc pe fiecare pozitie de ridicare:
   serie individuala (4403) -> cate una pe unitate primita;
   partida (4402) -> cel putin una; evidenta fara serie (4401) -> niciuna
   (regula de exceptie pentru produsele fara identificator, plan §9B). */
CREATE OR ALTER PROCEDURE SP_CW_PICKUP_MISSING_PHOTOS (
    A_PDOCID INTEGER)
RETURNS (
    O_ITEMID INTEGER,
    O_REQUIRED INTEGER,
    O_DONE INTEGER)
SQL SECURITY DEFINER
AS
BEGIN
    FOR SELECT I.ITEMID,
               CASE
                   WHEN COALESCE(I.QTY_DONE, 0) <= 0 THEN 0
                   WHEN I.SERIAL_TYPE_ID = 4403 THEN CEILING(I.QTY_DONE)
                   WHEN I.SERIAL_TYPE_ID = 4402 THEN 1
                   ELSE 0
               END,
               (SELECT COUNT(DISTINCT F.UNIT_NO) FROM TDB_PICKUP_PHOTO F
                WHERE F.ITEMID = I.ITEMID AND F.FLG_REPLACED = 0
                  AND F.UNIT_NO <= CEILING(COALESCE(I.QTY_DONE, 0)))
        FROM TDB_PICKUP_DOC_ITEM I
        WHERE I.PDOCID = :A_PDOCID AND I.ITEM_KIND = 1
        INTO :O_ITEMID, :O_REQUIRED, :O_DONE
    DO
        IF (O_DONE < O_REQUIRED) THEN
            SUSPEND;
END^

/* Inchiderea preluarii: reverifica blocarea, cantitatile si fotografiile si,
   intr-o singura tranzactie, creeaza Intrare marfa (106) DESCHISA in depozitul
   soferului - cate una pe furnizorul comercial (ORDER_SUPPLIERID) - apoi
   marcheaza preluarea Incarcat. La eroare nu se schimba nimic. Retransmiterea
   intoarce documentul deja creat (plan §8, §9B, scenariile 19, 20, 32). */
CREATE OR ALTER PROCEDURE SP_CW_PICKUP_CLOSE (
    A_PDOCID INTEGER,
    A_COURIERID INTEGER,
    A_UID VARCHAR(36))
RETURNS (
    O_INVOICE_DOCID INTEGER,
    O_INVOICES INTEGER)
SQL SECURITY DEFINER
AS
DECLARE VARIABLE V_STATE SMALLINT;
DECLARE VARIABLE V_COURIER INTEGER;
DECLARE VARIABLE V_STOPID INTEGER;
DECLARE VARIABLE V_ROUTEID INTEGER;
DECLARE VARIABLE V_FIRMAID INTEGER;
DECLARE VARIABLE V_STOCKID INTEGER;
DECLARE VARIABLE V_LOCKED INTEGER;
DECLARE VARIABLE V_WEB_USERID INTEGER;
DECLARE VARIABLE V_OLD_USERID VARCHAR(255);
DECLARE VARIABLE V_DTSC INTEGER;
DECLARE VARIABLE V_ACNT SMALLINT;
DECLARE VARIABLE V_RATEUSD DOUBLE PRECISION;
DECLARE VARIABLE V_SUPPLIER INTEGER;
DECLARE VARIABLE V_DOCID INTEGER;
DECLARE VARIABLE V_GOODSID INTEGER;
DECLARE VARIABLE V_QTY NUMERIC(15,4);
DECLARE VARIABLE V_PRICE DOUBLE PRECISION;
DECLARE VARIABLE V_PROBLEMS INTEGER;
DECLARE VARIABLE V_USER_SET SMALLINT = 0;
BEGIN
    SELECT FIRST 1 RESULT_DOCID FROM TDB_DISPATCH_LOG WHERE ACTION_UID = :A_UID INTO :O_INVOICE_DOCID;
    IF (ROW_COUNT > 0) THEN
    BEGIN
        SELECT COUNT(DISTINCT INVOICE_DOCID) FROM TDB_PICKUP_DOC_ITEM WHERE PDOCID = :A_PDOCID INTO :O_INVOICES;
        SUSPEND;
        EXIT;
    END

    /* blocarea documentului: doua inchideri simultane -> una singura trece */
    SELECT PDOCID, STATEID, COURIERID, STOPID, ROUTEID, FIRMAID, STOCKID
    FROM TDB_PICKUP_DOC
    WHERE PDOCID = :A_PDOCID
    FOR UPDATE WITH LOCK
    INTO :V_LOCKED, :V_STATE, :V_COURIER, :V_STOPID, :V_ROUTEID, :V_FIRMAID, :V_STOCKID;

    IF (V_LOCKED IS NULL OR V_COURIER IS DISTINCT FROM A_COURIERID) THEN
        EXCEPTION ERR_DISPATCH 'Preluarea nu exista sau apartine altui curier';
    IF (V_STATE = 2) THEN
    BEGIN
        /* deja inchisa (raspuns pierdut, alt identificator): acelasi rezultat */
        SELECT MIN(INVOICE_DOCID), COUNT(DISTINCT INVOICE_DOCID) FROM TDB_PICKUP_DOC_ITEM WHERE PDOCID = :A_PDOCID
        INTO :O_INVOICE_DOCID, :O_INVOICES;
        SUSPEND;
        EXIT;
    END
    IF (V_STATE <> 1) THEN
        EXCEPTION ERR_DISPATCH 'Preluarea a fost anulata';

    IF (EXISTS(SELECT 1 FROM TDB_PICKUP_DOC_ITEM WHERE PDOCID = :A_PDOCID AND QTY_DONE IS NULL)) THEN
        EXCEPTION ERR_DISPATCH 'Confirma cantitatea pentru fiecare produs';
    IF (EXISTS(SELECT 1 FROM SP_CW_PICKUP_MISSING_PHOTOS(:A_PDOCID))) THEN
        EXCEPTION ERR_DISPATCH 'Lipsesc fotografii ale seriilor sau partidelor';

    O_INVOICES = 0;

    IF (EXISTS(SELECT 1 FROM TDB_PICKUP_DOC_ITEM WHERE PDOCID = :A_PDOCID AND ITEM_KIND = 1 AND QTY_DONE > 0)) THEN
    BEGIN
        SELECT WEB_USERID FROM TS_DISPATCH_SETTINGS WHERE FIRMAID = :V_FIRMAID INTO :V_WEB_USERID;
        IF (V_WEB_USERID IS NULL) THEN
            EXCEPTION ERR_DISPATCH 'Dispeceratul nu este configurat pentru firma (TS_DISPATCH_SETTINGS)';

        SELECT FIRST 1 DTSC, FLG_ACNT FROM TS_DOCTYPES_DEFVALUES
        WHERE DOCTYPEID = 106 AND FIRMA = :V_FIRMAID
        INTO :V_DTSC, :V_ACNT;
        SELECT BNM_RATE FROM TS_CURRENCY WHERE CURRENCYID = 840 INTO :V_RATEUSD;

        /* documentele WMS cer utilizatorul sesiunii (CREATED_BY, perioada deschisa) */
        V_OLD_USERID = RDB$GET_CONTEXT('USER_SESSION', 'UserID');
        RDB$SET_CONTEXT('USER_SESSION', 'UserID', :V_WEB_USERID);
        V_USER_SET = 1;

        FOR SELECT DISTINCT ORDER_SUPPLIERID
            FROM TDB_PICKUP_DOC_ITEM
            WHERE PDOCID = :A_PDOCID AND ITEM_KIND = 1 AND QTY_DONE > 0
            INTO :V_SUPPLIER
        DO
        BEGIN
            INSERT INTO TDB_DOCS (DOCTYPEID, DATA, DT, CT, DTDEP, CTDEP, DTSC, CTSC, SC2, SUMA, VAT,
                                  CURRENCYID, RATE, RATEUSD, CONTRACTID, PARENTDOCID, FLAGS,
                                  CREATED_DATE, CREATED_BY, ACC$MASK)
            VALUES (106, CURRENT_TIMESTAMP, :V_FIRMAID, :V_SUPPLIER, :V_STOCKID, -1, COALESCE(:V_DTSC, -1), -1, -1, 0, 0,
                    498, 1, COALESCE(:V_RATEUSD, 1), -1, -1, IIF(COALESCE(:V_ACNT, 1) = 1, 2, 0),
                    CURRENT_TIMESTAMP, :V_WEB_USERID, 0)
            RETURNING DOCID INTO :V_DOCID;

            /* acelasi produs din mai multe comenzi = o singura linie (cheia TDB_JURNAL);
               pretul de achizitie se converteste in lei la cursul BNM */
            FOR SELECT I.GOODSID, SUM(I.QTY_DONE),
                       MAX(COALESCE(I.PRICE, 0) * COALESCE((SELECT C.BNM_RATE FROM TS_CURRENCY C WHERE C.CURRENCYID = I.CURRENCYID), 1))
                FROM TDB_PICKUP_DOC_ITEM I
                WHERE I.PDOCID = :A_PDOCID AND I.ITEM_KIND = 1 AND I.QTY_DONE > 0
                  AND I.ORDER_SUPPLIERID = :V_SUPPLIER
                GROUP BY I.GOODSID
                INTO :V_GOODSID, :V_QTY, :V_PRICE
            DO
                INSERT INTO TDB_JURNAL (DOCID, DTDEP, CTDEP, GOODSCOMPLECT_ID, GOODSID, UMID, QTY, PRICE, SUMA,
                                        SUMAVAT, WARRANTY, COST, FLAGS, CREATED_BY)
                SELECT :V_DOCID, :V_STOCKID, -1, -1, G.GOODSID, G.UMID, :V_QTY, ROUND(:V_PRICE, 2),
                       ROUND(:V_PRICE, 2) * :V_QTY, 0, COALESCE(G.WARRANTY, 0), ROUND(:V_PRICE, 2),
                       IIF(COALESCE(:V_ACNT, 1) = 1, 3, 1), :V_WEB_USERID
                FROM TS_GOODS G
                WHERE G.GOODSID = :V_GOODSID;

            RDB$SET_CONTEXT('USER_TRANSACTION', 'DISPATCH_PROC', '1');
            UPDATE TDB_PICKUP_DOC_ITEM SET INVOICE_DOCID = :V_DOCID
            WHERE PDOCID = :A_PDOCID AND ITEM_KIND = 1 AND QTY_DONE > 0 AND ORDER_SUPPLIERID = :V_SUPPLIER;

            IF (O_INVOICE_DOCID IS NULL) THEN
                O_INVOICE_DOCID = V_DOCID;
            O_INVOICES = O_INVOICES + 1;
        END

        RDB$SET_CONTEXT('USER_SESSION', 'UserID', :V_OLD_USERID);
        V_USER_SET = 0;
    END

    RDB$SET_CONTEXT('USER_TRANSACTION', 'DISPATCH_PROC', '1');

    /* ridicarile primite trec in "Ridicata"; cele cu 0 raman atribuite (problema) */
    UPDATE TDB_SUPPLIER_PICKUP P SET STATEID = 2
    WHERE P.STATEID IN (0, 1)
      AND EXISTS(SELECT 1 FROM TDB_PICKUP_DOC_ITEM I
                 WHERE I.PDOCID = :A_PDOCID AND I.PICKUPID = P.PICKUPID AND I.QTY_DONE > 0);

    /* sarcinile: executata daca s-a primit/predat tot, altfel problema */
    UPDATE TDB_DISPATCH_STOP_TASK T
    SET STATEID = IIF(EXISTS(SELECT 1 FROM TDB_PICKUP_DOC_ITEM I
                             WHERE I.PDOCID = :A_PDOCID AND I.TASKID = T.TASKID AND I.QTY_DONE < I.QTY_PLANNED), 2, 1)
    WHERE T.STATEID = 0
      AND EXISTS(SELECT 1 FROM TDB_PICKUP_DOC_ITEM I WHERE I.PDOCID = :A_PDOCID AND I.TASKID = T.TASKID);

    UPDATE TDB_PICKUP_DOC SET STATEID = 2, CLOSED_AT = CURRENT_TIMESTAMP, CLOSE_UID = :A_UID
    WHERE PDOCID = :A_PDOCID;

    SELECT COUNT(*) FROM TDB_PICKUP_DOC_ITEM WHERE PDOCID = :A_PDOCID AND QTY_DONE < QTY_PLANNED INTO :V_PROBLEMS;
    UPDATE TDB_DISPATCH_STOP SET STATEID = IIF(:V_PROBLEMS > 0, 3, 2), DONE_AT = CURRENT_TIMESTAMP
    WHERE STOPID = :V_STOPID AND STATEID IN (0, 1);

    INSERT INTO TDB_DISPATCH_LOG (ACTION_UID, ACTOR_KIND, ACTOR_ID, ACTION_CODE, ROUTEID, STOPID, PDOCID, RESULT_DOCID, NOTE)
    VALUES (:A_UID, 1, :A_COURIERID, 'PICKUP_CLOSE', :V_ROUTEID, :V_STOPID, :A_PDOCID, :O_INVOICE_DOCID,
            'Intrari create: ' || :O_INVOICES || IIF(:V_PROBLEMS > 0, ', pozitii cu lipsuri: ' || :V_PROBLEMS, ''));

    RDB$SET_CONTEXT('USER_TRANSACTION', 'DISPATCH_PROC', NULL);
    SUSPEND;

    WHEN ANY DO
    BEGIN
        /* utilizatorul sesiunii revine la cel dinainte, apoi eroarea merge mai departe */
        IF (V_USER_SET = 1) THEN
            RDB$SET_CONTEXT('USER_SESSION', 'UserID', :V_OLD_USERID);
        EXCEPTION;
    END
END^

