            'Ridicarea ' || :A_PICKUPID);
END^

/* Livrarea documentului A_DOCID (vanzare) in ziua A_DATE, zona A_ZONEID.
   Fara curier: livrarea ramane "de planificat" (zona si data salvate).
   Adresa, telefonul si intervalul se copiaza din TDB_DOCS_DELIVERY la prima planificare. */
CREATE OR ALTER PROCEDURE SP_DISPATCH_DELIVERY_ASSIGN (
    A_DOCID INTEGER,
    A_COURIERID INTEGER,
    A_DATE DATE,
    A_ZONEID INTEGER)
RETURNS (
    O_DELIVERYID INTEGER)
AS
DECLARE VARIABLE V_FIRMAID INTEGER;
DECLARE VARIABLE V_CLIENT INTEGER;
DECLARE VARIABLE V_CLIENT_NAME VARCHAR(255);
DECLARE VARIABLE V_STATE SMALLINT;
DECLARE VARIABLE V_ADDRESS VARCHAR(512);
DECLARE VARIABLE V_PHONE VARCHAR(60);
DECLARE VARIABLE V_TIME VARCHAR(32);
DECLARE VARIABLE V_ZONEID INTEGER;
DECLARE VARIABLE V_PLANID INTEGER;
DECLARE VARIABLE V_ROUTEID INTEGER;
DECLARE VARIABLE V_STOPID INTEGER;
DECLARE VARIABLE V_OLD_TASK INTEGER;
DECLARE VARIABLE V_OLD_ROUTE INTEGER;
BEGIN
    SELECT D.DT, D.CT, C.NAME
    FROM TDB_DOCS D
    LEFT JOIN TS_CUSTOMER C ON C.CUSTOMERID = D.CT
    WHERE D.DOCID = :A_DOCID
    INTO :V_FIRMAID, :V_CLIENT, :V_CLIENT_NAME;
    IF (V_FIRMAID IS NULL) THEN
        EXCEPTION ERR_DISPATCH 'Documentul nu exista';
    IF (A_DATE IS NULL) THEN
        EXCEPTION ERR_DISPATCH 'Alege data livrarii';
    IF (A_COURIERID IS NOT NULL AND NOT EXISTS(SELECT 1 FROM TS_COURIER
            WHERE CUSTOMERID = :A_COURIERID AND FLG_ACTIVE = 1 AND FLG_CAN_DELIVER = 1)) THEN
        EXCEPTION ERR_DISPATCH 'Curierul ales nu face livrari';

    SELECT FIRST 1 DELIVERYID, STATEID FROM TDB_DISPATCH_DELIVERY
    WHERE DOCID = :A_DOCID AND STATEID <> 6
    ORDER BY DELIVERYID DESC
    INTO :O_DELIVERYID, :V_STATE;

    IF (V_STATE IN (2, 3, 4)) THEN
        EXCEPTION ERR_DISPATCH 'Livrarea este deja in executare sau livrata';
    IF (O_DELIVERYID IS NULL OR V_STATE = 5) THEN
    BEGIN
        /* livrare noua (sau replanificarea uneia esuate - cea veche ramane in istoric) */
        SELECT DELIVERY_ADDRESS, PHONE_NUMBER, DELIVERY_TIME FROM TDB_DOCS_DELIVERY WHERE DOCID = :A_DOCID
        INTO :V_ADDRESS, :V_PHONE, :V_TIME;
        INSERT INTO TDB_DISPATCH_DELIVERY (DOCID, FIRMAID, PLAN_DATE, ZONEID, ADDRESS, CONTACT_NAME, PHONE, TIME_TEXT, STATEID)
        VALUES (:A_DOCID, :V_FIRMAID, :A_DATE, :A_ZONEID, TRIM(:V_ADDRESS), :V_CLIENT_NAME, TRIM(:V_PHONE), TRIM(:V_TIME), 0)
        RETURNING DELIVERYID INTO :O_DELIVERYID;
    END

    UPDATE TDB_DISPATCH_DELIVERY
    SET PLAN_DATE = :A_DATE,
        ZONEID = COALESCE(:A_ZONEID, ZONEID),
        COURIERID = :A_COURIERID,
        STATEID = IIF(:A_COURIERID IS NULL, 0, 1)
    WHERE DELIVERYID = :O_DELIVERYID;

    SELECT ZONEID, ADDRESS, PHONE, TIME_TEXT FROM TDB_DISPATCH_DELIVERY WHERE DELIVERYID = :O_DELIVERYID
    INTO :V_ZONEID, :V_ADDRESS, :V_PHONE, :V_TIME;

    IF (A_COURIERID IS NOT NULL) THEN
    BEGIN
        SELECT O_PLANID FROM SP_DISPATCH_PLAN_ENSURE(:V_FIRMAID, :A_DATE) INTO :V_PLANID;
        SELECT O_ROUTEID FROM SP_DISPATCH_ROUTE_ENSURE(:V_PLANID, :A_COURIERID) INTO :V_ROUTEID;
    END

    SELECT FIRST 1 T.TASKID, S.ROUTEID, T.STOPID
    FROM TDB_DISPATCH_STOP_TASK T
    JOIN TDB_DISPATCH_STOP S ON S.STOPID = T.STOPID
    WHERE T.DELIVERYID = :O_DELIVERYID AND T.STATEID <> 9
    INTO :V_OLD_TASK, :V_OLD_ROUTE, :V_STOPID;

    IF (V_OLD_TASK IS NOT NULL AND V_OLD_ROUTE IS NOT DISTINCT FROM V_ROUTEID) THEN
    BEGIN
        /* acelasi traseu: doar zona opririi se aliniaza */
        UPDATE TDB_DISPATCH_STOP SET ZONEID = :V_ZONEID
        WHERE STOPID = :V_STOPID AND ZONEID IS DISTINCT FROM :V_ZONEID;
        EXECUTE PROCEDURE SP_DISPATCH_PLAN_TOUCH(:V_PLANID);
        SUSPEND;
        EXIT;
    END

    IF (V_OLD_TASK IS NOT NULL) THEN
        EXECUTE PROCEDURE SP_DISPATCH_TASK_REMOVE(:V_OLD_TASK);

    IF (V_ROUTEID IS NOT NULL) THEN
    BEGIN
        /* acelasi client si aceeasi adresa pe traseu = o singura oprire */
        V_STOPID = NULL;
        SELECT FIRST 1 STOPID FROM TDB_DISPATCH_STOP
        WHERE ROUTEID = :V_ROUTEID AND STOP_KIND = 3 AND STATEID = 0
          AND PARTNERID IS NOT DISTINCT FROM :V_CLIENT AND ADDRESS IS NOT DISTINCT FROM :V_ADDRESS
        INTO :V_STOPID;
        IF (V_STOPID IS NULL) THEN
            INSERT INTO TDB_DISPATCH_STOP (ROUTEID, ORDERNO, STOP_KIND, PARTNERID, ZONEID, TITLE, ADDRESS,
                                           CONTACT_NAME, PHONE, PLAN_TIME)
            VALUES (:V_ROUTEID,
                    (SELECT COALESCE(MAX(ORDERNO), 0) + 1 FROM TDB_DISPATCH_STOP WHERE ROUTEID = :V_ROUTEID),
                    3, :V_CLIENT, :V_ZONEID, :V_CLIENT_NAME, :V_ADDRESS, :V_CLIENT_NAME, :V_PHONE, :V_TIME)
            RETURNING STOPID INTO :V_STOPID;

        INSERT INTO TDB_DISPATCH_STOP_TASK (STOPID, TASK_KIND, DELIVERYID, ORDERNO)
        VALUES (:V_STOPID, 3, :O_DELIVERYID,
                (SELECT COUNT(*) + 1 FROM TDB_DISPATCH_STOP_TASK WHERE STOPID = :V_STOPID));
        EXECUTE PROCEDURE SP_DISPATCH_PLAN_TOUCH(:V_PLANID);
    END

    INSERT INTO TDB_DISPATCH_LOG (ACTOR_KIND, ACTOR_ID, ACTION_CODE, PLANID, ROUTEID, STOPID, DELIVERYID, NOTE)
    VALUES (2, CAST(RDB$GET_CONTEXT('USER_SESSION', 'UserID') AS INTEGER), 'DELIVERY_ASSIGN', :V_PLANID,
            :V_ROUTEID, :V_STOPID, :O_DELIVERYID,
            'Documentul ' || :A_DOCID || IIF(:A_COURIERID IS NULL, ' fara curier', ' -> curier ' || :A_COURIERID));
    SUSPEND;
END^

