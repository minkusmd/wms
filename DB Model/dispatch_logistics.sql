    WHERE PICKUPID = :A_PICKUPID AND STATEID IN (0, 1) AND DRIVERID IS NOT NULL;
    RDB$SET_CONTEXT('USER_TRANSACTION', 'DISPATCH_PROC', NULL);

    INSERT INTO TDB_DISPATCH_LOG (ACTOR_KIND, ACTOR_ID, ACTION_CODE, NOTE)
