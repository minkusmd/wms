        EXCEPTION ERR_DISPATCH 'Cantitatea trebuie sa fie intre 0 si ' || CAST(V_PLANNED AS VARCHAR(20));
    IF (A_QTY_DONE < V_PLANNED AND TRIM(COALESCE(A_ISSUE_NOTE, '')) = '') THEN
        EXCEPTION ERR_DISPATCH 'Scrie motivul pentru cantitatea lipsa';

    RDB$SET_CONTEXT('USER_TRANSACTION', 'DISPATCH_PROC', '1');
    UPDATE TDB_PICKUP_DOC_ITEM
    SET QTY_DONE = :A_QTY_DONE,
        ISSUE_NOTE = NULLIF(TRIM(:A_ISSUE_NOTE), '')
    WHERE ITEMID = :A_ITEMID;
    RDB$SET_CONTEXT('USER_TRANSACTION', 'DISPATCH_PROC', NULL);
END^

