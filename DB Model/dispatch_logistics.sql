/* Publicarea planului (sau republicarea dupa modificari): refuzata daca exista erori. */
CREATE OR ALTER PROCEDURE SP_DISPATCH_PUBLISH (
    A_PLANID INTEGER)
RETURNS (
    O_VERSIONNO INTEGER)
AS
DECLARE VARIABLE V_STATE SMALLINT;
DECLARE VARIABLE V_PROBLEM VARCHAR(255);
BEGIN
    SELECT STATEID FROM TDB_DISPATCH_PLAN WHERE PLANID = :A_PLANID INTO :V_STATE;
    IF (V_STATE IS NULL) THEN
        EXCEPTION ERR_DISPATCH 'Planul nu exista';
    IF (V_STATE = 3) THEN
        EXCEPTION ERR_DISPATCH 'Planul zilei este inchis';
    IF (NOT EXISTS(SELECT 1 FROM TDB_DISPATCH_ROUTE WHERE PLANID = :A_PLANID)) THEN
        EXCEPTION ERR_DISPATCH 'Planul nu are niciun traseu';

    SELECT FIRST 1 O_PROBLEM FROM SP_DISPATCH_PLAN_PROBLEMS(:A_PLANID) WHERE O_LEVEL = 1 INTO :V_PROBLEM;
    IF (V_PROBLEM IS NOT NULL) THEN
        EXCEPTION ERR_DISPATCH 'Planul nu poate fi publicat: ' || V_PROBLEM;

    IF (V_STATE = 0) THEN
        UPDATE TDB_DISPATCH_PLAN SET STATEID = 1, PUBLISHED_BY = CAST(RDB$GET_CONTEXT('USER_SESSION', 'UserID') AS INTEGER)
        WHERE PLANID = :A_PLANID;
    ELSE
        UPDATE TDB_DISPATCH_PLAN SET VERSIONNO = VERSIONNO + 1, PUBLISHED_AT = CURRENT_TIMESTAMP,
            PUBLISHED_BY = CAST(RDB$GET_CONTEXT('USER_SESSION', 'UserID') AS INTEGER)
        WHERE PLANID = :A_PLANID;

    SELECT VERSIONNO FROM TDB_DISPATCH_PLAN WHERE PLANID = :A_PLANID INTO :O_VERSIONNO;
    INSERT INTO TDB_DISPATCH_LOG (ACTOR_KIND, ACTOR_ID, ACTION_CODE, PLANID, NOTE)
    VALUES (2, CAST(RDB$GET_CONTEXT('USER_SESSION', 'UserID') AS INTEGER), 'PLAN_PUBLISH', :A_PLANID,
            'Versiunea ' || :O_VERSIONNO);
    SUSPEND;
END^

