END^

/* traseul curierului in plan; la creare primeste oprirea Depozit (plan §9F) */
CREATE OR ALTER PROCEDURE SP_DISPATCH_ROUTE_ENSURE (
    A_PLANID INTEGER,
    A_COURIERID INTEGER)
RETURNS (
    O_ROUTEID INTEGER)
AS
DECLARE VARIABLE V_BASE INTEGER;
BEGIN
    IF (NOT EXISTS(SELECT 1 FROM TS_COURIER WHERE CUSTOMERID = :A_COURIERID AND FLG_ACTIVE = 1)) THEN
        EXCEPTION ERR_DISPATCH 'Curierul nu are profil activ in dispecerat';

    SELECT ROUTEID FROM TDB_DISPATCH_ROUTE
    WHERE PLANID = :A_PLANID AND COURIERID = :A_COURIERID AND TRIPNO = 1
    INTO :O_ROUTEID;

    IF (O_ROUTEID IS NULL) THEN
    BEGIN
        SELECT S.BASE_STOCKID
        FROM TDB_DISPATCH_PLAN P
        JOIN TS_DISPATCH_SETTINGS S ON S.FIRMAID = P.FIRMAID
        WHERE P.PLANID = :A_PLANID
        INTO :V_BASE;
        IF (V_BASE IS NULL) THEN
            EXCEPTION ERR_DISPATCH 'Dispeceratul nu este configurat pentru firma: lipseste depozitul de baza';

        INSERT INTO TDB_DISPATCH_ROUTE (PLANID, COURIERID, TRIPNO)
        VALUES (:A_PLANID, :A_COURIERID, 1)
        RETURNING ROUTEID INTO :O_ROUTEID;

        INSERT INTO TDB_DISPATCH_STOP (ROUTEID, ORDERNO, STOP_KIND, STOCKID, TITLE)
        VALUES (:O_ROUTEID, 0, 1, :V_BASE, (SELECT TITLE FROM TS_STOCKS WHERE STOCKID = :V_BASE));
    END
    SUSPEND;
END^

/* scoate o sarcina din traseu: stearsa inainte de publicare, anulata dupa */
CREATE OR ALTER PROCEDURE SP_DISPATCH_TASK_REMOVE (
    A_TASKID INTEGER)
AS
DECLARE VARIABLE V_STOPID INTEGER;
DECLARE VARIABLE V_TASK_STATE SMALLINT;
DECLARE VARIABLE V_STOP_KIND SMALLINT;
DECLARE VARIABLE V_STOP_STATE SMALLINT;
DECLARE VARIABLE V_PLANID INTEGER;
DECLARE VARIABLE V_PLAN_STATE SMALLINT;
BEGIN
    SELECT T.STOPID, T.STATEID, S.STOP_KIND, S.STATEID, P.PLANID, P.STATEID
    FROM TDB_DISPATCH_STOP_TASK T
    JOIN TDB_DISPATCH_STOP S ON S.STOPID = T.STOPID
    JOIN TDB_DISPATCH_ROUTE R ON R.ROUTEID = S.ROUTEID
    JOIN TDB_DISPATCH_PLAN P ON P.PLANID = R.PLANID
    WHERE T.TASKID = :A_TASKID
    INTO :V_STOPID, :V_TASK_STATE, :V_STOP_KIND, :V_STOP_STATE, :V_PLANID, :V_PLAN_STATE;

    IF (V_STOPID IS NULL OR V_TASK_STATE = 9) THEN
        EXIT;
    IF (V_TASK_STATE IN (1, 2)) THEN
        EXCEPTION ERR_DISPATCH 'Sarcina a fost deja executata de sofer si nu se mai muta';
    IF (EXISTS(SELECT 1 FROM TDB_PICKUP_DOC_ITEM I JOIN TDB_PICKUP_DOC D ON D.PDOCID = I.PDOCID
               WHERE I.TASKID = :A_TASKID AND D.STATEID IN (1, 2))) THEN
        EXCEPTION ERR_DISPATCH 'Soferul a inceput deja preluarea: sarcina nu se mai muta';

    IF (V_PLAN_STATE = 0) THEN
    BEGIN
        DELETE FROM TDB_DISPATCH_STOP_TASK WHERE TASKID = :A_TASKID;
        IF (V_STOP_KIND <> 1 AND NOT EXISTS(SELECT 1 FROM TDB_DISPATCH_STOP_TASK WHERE STOPID = :V_STOPID)) THEN
            DELETE FROM TDB_DISPATCH_STOP WHERE STOPID = :V_STOPID;
    END
    ELSE
    BEGIN
        UPDATE TDB_DISPATCH_STOP_TASK SET STATEID = 9 WHERE TASKID = :A_TASKID;
        IF (V_STOP_KIND <> 1 AND V_STOP_STATE = 0
            AND NOT EXISTS(SELECT 1 FROM TDB_DISPATCH_STOP_TASK WHERE STOPID = :V_STOPID AND STATEID <> 9)) THEN
            UPDATE TDB_DISPATCH_STOP SET STATEID = 4 WHERE STOPID = :V_STOPID;
        EXECUTE PROCEDURE SP_DISPATCH_PLAN_TOUCH(:V_PLANID);
    END
END^

/* oprirea la furnizor pe traseu: una neinceputa pentru acelasi furnizor (consolidare,
   plan §7) sau una noua cu punctul de preluare implicit / adresa si telefonul din WMS */
CREATE OR ALTER PROCEDURE SP_DISPATCH_SUPPLIER_STOP (
    A_ROUTEID INTEGER,
    A_SUPPLIERID INTEGER)
RETURNS (
    O_STOPID INTEGER)
AS
DECLARE VARIABLE V_POINTID INTEGER;
DECLARE VARIABLE V_ADDRESS VARCHAR(512);
DECLARE VARIABLE V_ZONEID INTEGER;
DECLARE VARIABLE V_CONTACT VARCHAR(128);
DECLARE VARIABLE V_PHONE VARCHAR(60);
DECLARE VARIABLE V_LAT DECIMAL(9,6);
DECLARE VARIABLE V_LNG DECIMAL(9,6);
BEGIN
    SELECT FIRST 1 S.STOPID
    FROM TDB_DISPATCH_STOP S
    WHERE S.ROUTEID = :A_ROUTEID AND S.STOP_KIND = 2 AND S.PARTNERID = :A_SUPPLIERID AND S.STATEID = 0
      AND NOT EXISTS(SELECT 1 FROM TDB_PICKUP_DOC D WHERE D.STOPID = S.STOPID)
    ORDER BY S.ORDERNO
    INTO :O_STOPID;
    IF (O_STOPID IS NOT NULL) THEN
    BEGIN
        SUSPEND;
        EXIT;
    END

    SELECT FIRST 1 POINTID, ADDRESS, ZONEID, CONTACT_NAME, PHONE, LATITUDE, LONGITUDE
    FROM TS_PICKUP_POINT
    WHERE SUPPLIERID = :A_SUPPLIERID AND FLG_ACTIVE = 1
    ORDER BY FLG_DEFAULT DESC, POINTID
    INTO :V_POINTID, :V_ADDRESS, :V_ZONEID, :V_CONTACT, :V_PHONE, :V_LAT, :V_LNG;

    IF (V_POINTID IS NULL) THEN
    BEGIN
        /* adresa fizica (7662) inaintea celei juridice; STREET contine de obicei si localitatea */
        SELECT FIRST 1 TRIM(STREET) FROM TS_CUST_ADDR
        WHERE CUSTOMERID = :A_SUPPLIERID AND TRIM(COALESCE(STREET, '')) <> ''
        ORDER BY IIF(ADDRTYPEID = 7662, 0, 1), ADDRID
        INTO :V_ADDRESS;
        SELECT FIRST 1 PHONENUMBER, COMMENT FROM TS_CUST_PHONES
        WHERE CUSTOMERID = :A_SUPPLIERID AND TRIM(COALESCE(PHONENUMBER, '')) <> ''
        ORDER BY PHONEID
        INTO :V_PHONE, :V_CONTACT;
    END

    INSERT INTO TDB_DISPATCH_STOP (ROUTEID, ORDERNO, STOP_KIND, PARTNERID, POINTID, ZONEID, TITLE,
                                   ADDRESS, CONTACT_NAME, PHONE, LATITUDE, LONGITUDE)
    VALUES (:A_ROUTEID,
            (SELECT COALESCE(MAX(ORDERNO), 0) + 1 FROM TDB_DISPATCH_STOP WHERE ROUTEID = :A_ROUTEID),
            2, :A_SUPPLIERID, :V_POINTID, :V_ZONEID,
            (SELECT NAME FROM TS_CUSTOMER WHERE CUSTOMERID = :A_SUPPLIERID),
            :V_ADDRESS, :V_CONTACT, :V_PHONE, :V_LAT, :V_LNG)
    RETURNING STOPID INTO :O_STOPID;
    SUSPEND;
END^

/* Ridicarea de la furnizor pe traseul curierului, in ziua A_DATE. Repetarea
   cu acelasi curier si zi nu schimba nimic; alt curier/alta zi muta sarcina. */
CREATE OR ALTER PROCEDURE SP_DISPATCH_PICKUP_ASSIGN (
    A_PICKUPID INTEGER,
    A_COURIERID INTEGER,
    A_DATE DATE)
RETURNS (
    O_STOPID INTEGER)
AS
DECLARE VARIABLE V_STATE SMALLINT;
DECLARE VARIABLE V_SUPPLIER INTEGER;
DECLARE VARIABLE V_FIRMAID INTEGER;
DECLARE VARIABLE V_PLANID INTEGER;
DECLARE VARIABLE V_ROUTEID INTEGER;
DECLARE VARIABLE V_OLD_TASK INTEGER;
DECLARE VARIABLE V_OLD_ROUTE INTEGER;
DECLARE VARIABLE V_OLD_STOP INTEGER;
BEGIN
    SELECT P.STATEID, P.PICKUP_SUPPLIERID, D.DT
    FROM TDB_SUPPLIER_PICKUP P
    JOIN TDB_DOCS D ON D.DOCID = P.DOCID
    WHERE P.PICKUPID = :A_PICKUPID
    INTO :V_STATE, :V_SUPPLIER, :V_FIRMAID;

    IF (V_STATE IS NULL) THEN
        EXCEPTION ERR_DISPATCH 'Ridicarea nu exista';
    IF (V_STATE NOT IN (0, 1)) THEN
        EXCEPTION ERR_DISPATCH 'Ridicarea este deja ridicata sau anulata';
    IF (NOT EXISTS(SELECT 1 FROM TS_COURIER WHERE CUSTOMERID = :A_COURIERID AND FLG_ACTIVE = 1 AND FLG_CAN_PICKUP = 1)) THEN
        EXCEPTION ERR_DISPATCH 'Curierul ales nu face ridicari de la furnizori';

    SELECT O_PLANID FROM SP_DISPATCH_PLAN_ENSURE(:V_FIRMAID, :A_DATE) INTO :V_PLANID;
    SELECT O_ROUTEID FROM SP_DISPATCH_ROUTE_ENSURE(:V_PLANID, :A_COURIERID) INTO :V_ROUTEID;

    SELECT FIRST 1 T.TASKID, S.ROUTEID, T.STOPID
    FROM TDB_DISPATCH_STOP_TASK T
    JOIN TDB_DISPATCH_STOP S ON S.STOPID = T.STOPID
    WHERE T.PICKUPID = :A_PICKUPID AND T.STATEID <> 9
    INTO :V_OLD_TASK, :V_OLD_ROUTE, :V_OLD_STOP;

    IF (V_OLD_ROUTE = V_ROUTEID) THEN
        O_STOPID = V_OLD_STOP;
    ELSE
    BEGIN
        IF (V_OLD_TASK IS NOT NULL) THEN
            EXECUTE PROCEDURE SP_DISPATCH_TASK_REMOVE(:V_OLD_TASK);

        SELECT O_STOPID FROM SP_DISPATCH_SUPPLIER_STOP(:V_ROUTEID, :V_SUPPLIER) INTO :O_STOPID;
        INSERT INTO TDB_DISPATCH_STOP_TASK (STOPID, TASK_KIND, PICKUPID, ORDERNO)
        VALUES (:O_STOPID, 1, :A_PICKUPID,
                (SELECT COUNT(*) + 1 FROM TDB_DISPATCH_STOP_TASK WHERE STOPID = :O_STOPID));
        EXECUTE PROCEDURE SP_DISPATCH_PLAN_TOUCH(:V_PLANID);

        INSERT INTO TDB_DISPATCH_LOG (ACTOR_KIND, ACTOR_ID, ACTION_CODE, PLANID, ROUTEID, STOPID, NOTE)
        VALUES (2, CAST(RDB$GET_CONTEXT('USER_SESSION', 'UserID') AS INTEGER), 'PICKUP_ASSIGN', :V_PLANID,
                :V_ROUTEID, :O_STOPID, 'Ridicarea ' || :A_PICKUPID || ' -> curier ' || :A_COURIERID);
    END

    /* copia din ridicare (sofer, data) se aliniaza cu traseul */
    RDB$SET_CONTEXT('USER_TRANSACTION', 'DISPATCH_PROC', '1');
    UPDATE TDB_SUPPLIER_PICKUP SET DRIVERID = :A_COURIERID, PLAN_DATE = :A_DATE
    WHERE PICKUPID = :A_PICKUPID
      AND (DRIVERID IS DISTINCT FROM :A_COURIERID OR PLAN_DATE IS DISTINCT FROM :A_DATE);
    RDB$SET_CONTEXT('USER_TRANSACTION', 'DISPATCH_PROC', NULL);
    SUSPEND;
END^

CREATE OR ALTER PROCEDURE SP_DISPATCH_PICKUP_UNASSIGN (
    A_PICKUPID INTEGER)
AS
DECLARE VARIABLE V_TASK INTEGER;
BEGIN
    FOR SELECT TASKID FROM TDB_DISPATCH_STOP_TASK WHERE PICKUPID = :A_PICKUPID AND STATEID <> 9
        INTO :V_TASK
