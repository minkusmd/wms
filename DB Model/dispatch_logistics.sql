/* Codul de activare a contului web (apelat din WMS de dispecer). Intoarce
   codul o singura data; in baza ramane doar hash-ul SHA-256 (24 de ore).
   Parola veche si sesiunile "tine-ma minte" se anuleaza. */
CREATE OR ALTER PROCEDURE SP_COURIER_WEB_ACTIVATION (
    A_CUSTOMERID INTEGER)
RETURNS (
    O_CODE VARCHAR(8))
AS
BEGIN
    IF (NOT EXISTS(SELECT 1 FROM TS_COURIER WHERE CUSTOMERID = :A_CUSTOMERID AND FLG_ACTIVE = 1
                   AND WEB_LOGIN IS NOT NULL)) THEN
        EXCEPTION ERR_DISPATCH 'Curierul nu are profil activ sau login web';

    O_CODE = LPAD(CAST(MOD(ABS(CAST(RAND() * 2147483647 AS BIGINT)
                              + CAST(EXTRACT(MILLISECOND FROM CURRENT_TIMESTAMP) AS BIGINT) * 7919), 100000000)
                       AS VARCHAR(8)), 8, '0');

    UPDATE TS_COURIER
    SET WEB_ACTIVATION_HASH = LOWER(HEX_ENCODE(CRYPT_HASH(:O_CODE USING SHA256))),
        WEB_ACTIVATION_EXPIRES = DATEADD(24 HOUR TO CURRENT_TIMESTAMP),
        WEB_PASSWORD_HASH = NULL,
        WEB_REMEMBER_TOKEN = NULL
    WHERE CUSTOMERID = :A_CUSTOMERID;

    SUSPEND;
END^

/* Inceperea preluarii la furnizor: fixeaza lista (ridicari + retururi ale
   opririi), blocheaza randurile din TDB_SUPPLIER_PICKUP si inregistreaza
   curierul si ora. Reluarea (acelasi A_UID sau document deja deschis)
   intoarce documentul existent. */
CREATE OR ALTER PROCEDURE SP_CW_PICKUP_START (
    A_STOPID INTEGER,
    A_COURIERID INTEGER,
    A_UID VARCHAR(36))
RETURNS (
    O_PDOCID INTEGER)
SQL SECURITY DEFINER
AS
DECLARE VARIABLE V_ROUTEID INTEGER;
DECLARE VARIABLE V_PLANID INTEGER;
DECLARE VARIABLE V_KIND SMALLINT;
DECLARE VARIABLE V_STOP_STATE SMALLINT;
DECLARE VARIABLE V_PARTNERID INTEGER;
DECLARE VARIABLE V_ROUTE_COURIER INTEGER;
DECLARE VARIABLE V_PLAN_STATE SMALLINT;
DECLARE VARIABLE V_PLAN_DATE DATE;
DECLARE VARIABLE V_FIRMAID INTEGER;
DECLARE VARIABLE V_STOCKID INTEGER;
DECLARE VARIABLE V_TASKID INTEGER;
DECLARE VARIABLE V_PICKUPID INTEGER;
DECLARE VARIABLE V_DOCID INTEGER;
DECLARE VARIABLE V_DTDEP INTEGER;
DECLARE VARIABLE V_CTDEP INTEGER;
DECLARE VARIABLE V_GOODSID INTEGER;
DECLARE VARIABLE V_CODE VARCHAR(128);
DECLARE VARIABLE V_QTY NUMERIC(15,4);
DECLARE VARIABLE V_ORDER_SUPPLIER INTEGER;
DECLARE VARIABLE V_PRICE DOUBLE PRECISION;
DECLARE VARIABLE V_CURRENCY INTEGER;
DECLARE VARIABLE V_LOCKED INTEGER;
DECLARE VARIABLE V_ITEMS INTEGER = 0;
BEGIN
    SELECT PDOCID FROM TDB_DISPATCH_LOG WHERE ACTION_UID = :A_UID INTO :O_PDOCID;
    IF (O_PDOCID IS NOT NULL) THEN
    BEGIN
        SUSPEND;
        EXIT;
    END

    SELECT S.ROUTEID, S.STOP_KIND, S.STATEID, S.PARTNERID, R.COURIERID, R.PLANID, P.STATEID, P.PLAN_DATE, P.FIRMAID
    FROM TDB_DISPATCH_STOP S
    JOIN TDB_DISPATCH_ROUTE R ON R.ROUTEID = S.ROUTEID
    JOIN TDB_DISPATCH_PLAN P ON P.PLANID = R.PLANID
    WHERE S.STOPID = :A_STOPID
    INTO :V_ROUTEID, :V_KIND, :V_STOP_STATE, :V_PARTNERID, :V_ROUTE_COURIER, :V_PLANID, :V_PLAN_STATE, :V_PLAN_DATE, :V_FIRMAID;

    IF (V_ROUTEID IS NULL OR V_ROUTE_COURIER IS DISTINCT FROM A_COURIERID) THEN
        EXCEPTION ERR_DISPATCH 'Oprirea nu este pe traseul tau';
    IF (V_PLAN_STATE NOT IN (1, 2)) THEN
        EXCEPTION ERR_DISPATCH 'Traseul nu este publicat';
    IF (V_KIND <> 2) THEN
        EXCEPTION ERR_DISPATCH 'Oprirea nu este la un furnizor';
    IF (V_STOP_STATE = 4) THEN
        EXCEPTION ERR_DISPATCH 'Oprirea a fost anulata de dispecer';

    /* documentul deja inceput (browser inchis, internet pierdut): se continua */
    SELECT PDOCID FROM TDB_PICKUP_DOC WHERE STOPID = :A_STOPID AND STATEID = 1 INTO :O_PDOCID;
    IF (O_PDOCID IS NOT NULL) THEN
    BEGIN
        SUSPEND;
        EXIT;
    END

    SELECT STOCKID FROM TS_COURIER WHERE CUSTOMERID = :A_COURIERID AND FLG_ACTIVE = 1 INTO :V_STOCKID;
    IF (V_STOCKID IS NULL) THEN
        EXCEPTION ERR_DISPATCH 'Curierul nu are depozit asociat. Anunta dispecerul.';

    RDB$SET_CONTEXT('USER_TRANSACTION', 'DISPATCH_PROC', '1');

    INSERT INTO TDB_PICKUP_DOC (STOPID, ROUTEID, COURIERID, SUPPLIERID, FIRMAID, STOCKID, STATEID, STARTED_AT, START_UID)
    VALUES (:A_STOPID, :V_ROUTEID, :A_COURIERID, :V_PARTNERID, :V_FIRMAID, :V_STOCKID, 1, CURRENT_TIMESTAMP, :A_UID)
    RETURNING PDOCID INTO :O_PDOCID;

    /* ridicarile active ale opririi, neincluse in alta preluare deschisa/incarcata */
    FOR SELECT T.TASKID, T.PICKUPID
        FROM TDB_DISPATCH_STOP_TASK T
        WHERE T.STOPID = :A_STOPID AND T.TASK_KIND = 1 AND T.STATEID = 0
          AND NOT EXISTS(SELECT 1 FROM TDB_PICKUP_DOC_ITEM I JOIN TDB_PICKUP_DOC D ON D.PDOCID = I.PDOCID
                         WHERE I.TASKID = T.TASKID AND D.STATEID IN (1, 2))
        ORDER BY T.ORDERNO, T.TASKID
        INTO :V_TASKID, :V_PICKUPID
    DO
    BEGIN
        /* blocarea randului: o modificare concurenta din WMS fie s-a terminat
           inainte (si e inclusa), fie asteapta si e respinsa de trigger dupa */
        V_LOCKED = NULL;
        SELECT PICKUPID, DOCID, DTDEP, GOODSID, GOODS_CODE, QTY, ORDER_SUPPLIERID
        FROM TDB_SUPPLIER_PICKUP
        WHERE PICKUPID = :V_PICKUPID AND STATEID IN (0, 1)
        FOR UPDATE WITH LOCK
        INTO :V_LOCKED, :V_DOCID, :V_DTDEP, :V_GOODSID, :V_CODE, :V_QTY, :V_ORDER_SUPPLIER;

        IF (V_LOCKED IS NOT NULL) THEN
        BEGIN
            V_PRICE = NULL;
            V_CURRENCY = NULL;
            SELECT FIRST 1 PRICE0, CURRENCY0ID
            FROM TS_GOODS_FOREIGN
            WHERE GOODSID = :V_GOODSID AND CUSTOMERID = :V_ORDER_SUPPLIER
            INTO :V_PRICE, :V_CURRENCY;

            INSERT INTO TDB_PICKUP_DOC_ITEM (PDOCID, TASKID, ITEM_KIND, PICKUPID, SRC_DOCID, SRC_DTDEP,
                                             ORDER_SUPPLIERID, GOODSID, GOODS_CODE, SERIAL_TYPE_ID,
                                             QTY_PLANNED, PRICE, CURRENCYID)
            VALUES (:O_PDOCID, :V_TASKID, 1, :V_PICKUPID, :V_DOCID, :V_DTDEP,
                    :V_ORDER_SUPPLIER, :V_GOODSID, :V_CODE,
                    (SELECT SERIAL_TYPE_ID FROM TS_GOODS WHERE GOODSID = :V_GOODSID),
                    :V_QTY, :V_PRICE, :V_CURRENCY);

            /* sursa unica pentru curier si data: copia din ridicare se aliniaza */
            UPDATE TDB_SUPPLIER_PICKUP
            SET DRIVERID = :A_COURIERID, PLAN_DATE = :V_PLAN_DATE
            WHERE PICKUPID = :V_PICKUPID
              AND (DRIVERID IS DISTINCT FROM :A_COURIERID OR PLAN_DATE IS DISTINCT FROM :V_PLAN_DATE);

            V_ITEMS = V_ITEMS + 1;
        END
    END

    /* retururile la furnizor ale opririi: liniile documentului de retur */
    FOR SELECT T.TASKID, T.DOCID
        FROM TDB_DISPATCH_STOP_TASK T
        WHERE T.STOPID = :A_STOPID AND T.TASK_KIND = 2 AND T.STATEID = 0
          AND NOT EXISTS(SELECT 1 FROM TDB_PICKUP_DOC_ITEM I JOIN TDB_PICKUP_DOC D ON D.PDOCID = I.PDOCID
                         WHERE I.TASKID = T.TASKID AND D.STATEID IN (1, 2))
        ORDER BY T.ORDERNO, T.TASKID
        INTO :V_TASKID, :V_DOCID
    DO
    BEGIN
        FOR SELECT J.DTDEP, J.CTDEP, J.GOODSID, J.QTY, J.PRICE, D.CURRENCYID, D.CT
            FROM TDB_JURNAL J
            JOIN TDB_DOCS D ON D.DOCID = J.DOCID
            WHERE J.DOCID = :V_DOCID AND J.GOODSCOMPLECT_ID = -1 AND J.QTY > 0
            INTO :V_DTDEP, :V_CTDEP, :V_GOODSID, :V_QTY, :V_PRICE, :V_CURRENCY, :V_ORDER_SUPPLIER
        DO
        BEGIN
            INSERT INTO TDB_PICKUP_DOC_ITEM (PDOCID, TASKID, ITEM_KIND, SRC_DOCID, SRC_DTDEP, SRC_CTDEP,
                                             ORDER_SUPPLIERID, GOODSID, GOODS_CODE, SERIAL_TYPE_ID,
                                             QTY_PLANNED, PRICE, CURRENCYID)
            VALUES (:O_PDOCID, :V_TASKID, 2, :V_DOCID, :V_DTDEP, :V_CTDEP,
                    :V_ORDER_SUPPLIER, :V_GOODSID,
                    (SELECT CODE FROM TS_GOODS WHERE GOODSID = :V_GOODSID),
                    (SELECT SERIAL_TYPE_ID FROM TS_GOODS WHERE GOODSID = :V_GOODSID),
                    :V_QTY, :V_PRICE, :V_CURRENCY);
            V_ITEMS = V_ITEMS + 1;
        END
    END

    IF (V_ITEMS = 0) THEN
        EXCEPTION ERR_DISPATCH 'La aceasta oprire nu exista produse de preluat sau de returnat';

    UPDATE TDB_DISPATCH_STOP
    SET STATEID = 1, ARRIVED_AT = COALESCE(ARRIVED_AT, CURRENT_TIMESTAMP)
    WHERE STOPID = :A_STOPID AND STATEID IN (0, 1);

    UPDATE TDB_DISPATCH_ROUTE
    SET STATEID = 1, STARTED_AT = COALESCE(STARTED_AT, CURRENT_TIMESTAMP)
    WHERE ROUTEID = :V_ROUTEID AND STATEID = 0;

    UPDATE TDB_DISPATCH_PLAN SET STATEID = 2 WHERE PLANID = :V_PLANID AND STATEID = 1;

    INSERT INTO TDB_DISPATCH_LOG (ACTION_UID, ACTOR_KIND, ACTOR_ID, ACTION_CODE, PLANID, ROUTEID, STOPID, PDOCID, NOTE)
    VALUES (:A_UID, 1, :A_COURIERID, 'PICKUP_START', :V_PLANID, :V_ROUTEID, :A_STOPID, :O_PDOCID,
            'Pozitii fixate: ' || :V_ITEMS);

    RDB$SET_CONTEXT('USER_TRANSACTION', 'DISPATCH_PROC', NULL);
    SUSPEND;
END^

/* Cantitatea primita/predata efectiv si nota de problema (lipsa, refuz) pe o pozitie. */
CREATE OR ALTER PROCEDURE SP_CW_PICKUP_ITEM_SET (
    A_ITEMID INTEGER,
    A_COURIERID INTEGER,
    A_QTY_DONE NUMERIC(15,4),
    A_ISSUE_NOTE VARCHAR(512))
SQL SECURITY DEFINER
AS
DECLARE VARIABLE V_STATE SMALLINT;
DECLARE VARIABLE V_COURIER INTEGER;
DECLARE VARIABLE V_PLANNED NUMERIC(15,4);
BEGIN
    SELECT D.STATEID, D.COURIERID, I.QTY_PLANNED
    FROM TDB_PICKUP_DOC_ITEM I
    JOIN TDB_PICKUP_DOC D ON D.PDOCID = I.PDOCID
    WHERE I.ITEMID = :A_ITEMID
    INTO :V_STATE, :V_COURIER, :V_PLANNED;

    IF (V_COURIER IS DISTINCT FROM A_COURIERID) THEN
        EXCEPTION ERR_DISPATCH 'Preluarea apartine altui curier';
