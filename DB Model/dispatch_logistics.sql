/* Muta oprirea cu o pozitie (A_DELTA = -1 sus, 1 jos). Oprirea Depozit ramane prima. */
CREATE OR ALTER PROCEDURE SP_DISPATCH_STOP_MOVE (
    A_STOPID INTEGER,
    A_DELTA SMALLINT)
AS
DECLARE VARIABLE V_ROUTEID INTEGER;
DECLARE VARIABLE V_KIND SMALLINT;
DECLARE VARIABLE V_PLANID INTEGER;
DECLARE VARIABLE V_STOP INTEGER;
DECLARE VARIABLE V_I INTEGER = 0;
DECLARE VARIABLE V_POS INTEGER;
DECLARE VARIABLE V_OTHER INTEGER;
DECLARE VARIABLE V_OTHER_KIND SMALLINT;
BEGIN
    SELECT S.ROUTEID, S.STOP_KIND, R.PLANID FROM TDB_DISPATCH_STOP S
    JOIN TDB_DISPATCH_ROUTE R ON R.ROUTEID = S.ROUTEID
    WHERE S.STOPID = :A_STOPID INTO :V_ROUTEID, :V_KIND, :V_PLANID;
    IF (V_ROUTEID IS NULL OR V_KIND = 1 OR A_DELTA NOT IN (-1, 1)) THEN
        EXIT;

    /* renumerotare 10, 20, 30 ... in ordinea curenta */
    FOR SELECT STOPID FROM TDB_DISPATCH_STOP WHERE ROUTEID = :V_ROUTEID
        ORDER BY IIF(STOP_KIND = 1, 0, 1), ORDERNO, STOPID
        INTO :V_STOP
    DO
    BEGIN
        V_I = V_I + 10;
        UPDATE TDB_DISPATCH_STOP SET ORDERNO = :V_I WHERE STOPID = :V_STOP AND ORDERNO <> :V_I;
        IF (V_STOP = A_STOPID) THEN
            V_POS = V_I;
    END

    SELECT STOPID, STOP_KIND FROM TDB_DISPATCH_STOP
    WHERE ROUTEID = :V_ROUTEID AND ORDERNO = :V_POS + 10 * :A_DELTA
    INTO :V_OTHER, :V_OTHER_KIND;
    IF (V_OTHER IS NULL OR V_OTHER_KIND = 1) THEN
        EXIT;

    UPDATE TDB_DISPATCH_STOP SET ORDERNO = :V_POS WHERE STOPID = :V_OTHER;
    UPDATE TDB_DISPATCH_STOP SET ORDERNO = :V_POS + 10 * :A_DELTA WHERE STOPID = :A_STOPID;
    EXECUTE PROCEDURE SP_DISPATCH_PLAN_TOUCH(:V_PLANID);
END^

/* Problemele planului: O_LEVEL 1 = eroare (blocheaza publicarea), 2 = avertisment. */
CREATE OR ALTER PROCEDURE SP_DISPATCH_PLAN_PROBLEMS (
    A_PLANID INTEGER)
RETURNS (
    O_LEVEL SMALLINT,
    O_COURIER_NAME VARCHAR(255),
    O_STOPID INTEGER,
    O_DOCID INTEGER,
    O_PROBLEM VARCHAR(255))
AS
DECLARE VARIABLE V_FIRMAID INTEGER;
DECLARE VARIABLE V_DATE DATE;
BEGIN
    SELECT FIRMAID, PLAN_DATE FROM TDB_DISPATCH_PLAN WHERE PLANID = :A_PLANID INTO :V_FIRMAID, :V_DATE;

    /* curierii traseelor */
    FOR SELECT IIF(K.CUSTOMERID IS NULL OR K.FLG_ACTIVE = 0 OR K.STOCKID IS NULL, 1, 2), C.NAME,
               CASE
                   WHEN K.CUSTOMERID IS NULL OR K.FLG_ACTIVE = 0 THEN 'Curierul nu are profil activ'
                   WHEN K.STOCKID IS NULL THEN 'Curierul nu are depozit (masina) asociat'
                   ELSE 'Curierul nu are cont in aplicatie: traseul se poate da doar tiparit'
               END
        FROM TDB_DISPATCH_ROUTE R
        JOIN TS_CUSTOMER C ON C.CUSTOMERID = R.COURIERID
        LEFT JOIN TS_COURIER K ON K.CUSTOMERID = R.COURIERID
        WHERE R.PLANID = :A_PLANID
          AND (K.CUSTOMERID IS NULL OR K.FLG_ACTIVE = 0 OR K.STOCKID IS NULL OR K.WEB_PASSWORD_HASH IS NULL)
        INTO :O_LEVEL, :O_COURIER_NAME, :O_PROBLEM
    DO
    BEGIN
        O_STOPID = NULL;
        O_DOCID = NULL;
        SUSPEND;
    END

    /* opririle active */
    FOR SELECT S.STOPID, C.NAME,
               CASE
                   WHEN TRIM(COALESCE(S.ADDRESS, '')) = '' AND S.STOP_KIND <> 1 THEN 1
                   WHEN S.ZONEID IS NULL AND S.STOP_KIND = 3 THEN 1
                   ELSE 2
               END,
               CASE
                   WHEN TRIM(COALESCE(S.ADDRESS, '')) = '' AND S.STOP_KIND <> 1 THEN 'Oprire fara adresa: ' || COALESCE(S.TITLE, '')
                   WHEN S.ZONEID IS NULL AND S.STOP_KIND = 3 THEN 'Livrare fara zona: ' || COALESCE(S.TITLE, '')
                   ELSE 'Furnizor fara zona: ' || COALESCE(S.TITLE, '')
               END
        FROM TDB_DISPATCH_STOP S
        JOIN TDB_DISPATCH_ROUTE R ON R.ROUTEID = S.ROUTEID
        JOIN TS_CUSTOMER C ON C.CUSTOMERID = R.COURIERID
        WHERE R.PLANID = :A_PLANID AND S.STATEID IN (0, 1)
          AND ((TRIM(COALESCE(S.ADDRESS, '')) = '' AND S.STOP_KIND <> 1)
               OR (S.ZONEID IS NULL AND S.STOP_KIND IN (2, 3)))
        ORDER BY C.NAME, S.ORDERNO
        INTO :O_STOPID, :O_COURIER_NAME, :O_LEVEL, :O_PROBLEM
    DO
    BEGIN
        O_DOCID = NULL;
        SUSPEND;
    END

    /* ce a ramas neatribuit pentru ziua planului */
    O_STOPID = NULL;
    O_COURIER_NAME = NULL;
    O_LEVEL = 2;
    FOR SELECT P.DOCID, 'Ridicare fara curier: ' || COALESCE(G.TITLE, '')
        FROM TDB_SUPPLIER_PICKUP P
        JOIN TDB_DOCS D ON D.DOCID = P.DOCID
        LEFT JOIN TS_GOODS G ON G.GOODSID = P.GOODSID
        WHERE D.DT = :V_FIRMAID AND P.PLAN_DATE = :V_DATE AND P.STATEID IN (0, 1)
          AND NOT EXISTS(SELECT 1 FROM TDB_DISPATCH_STOP_TASK T WHERE T.PICKUPID = P.PICKUPID AND T.STATEID <> 9)
        INTO :O_DOCID, :O_PROBLEM
    DO
        SUSPEND;
    FOR SELECT L.DOCID, 'Livrare fara curier: ' || COALESCE(L.CONTACT_NAME, '')
        FROM TDB_DISPATCH_DELIVERY L
        WHERE L.FIRMAID = :V_FIRMAID AND L.PLAN_DATE = :V_DATE AND L.STATEID = 0
        INTO :O_DOCID, :O_PROBLEM
