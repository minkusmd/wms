EXECUTE BLOCK AS BEGIN
  IF (EXISTS(SELECT 1 FROM RDB$GENERATORS WHERE RDB$GENERATOR_NAME = 'SQ_TS_GOODS_NAME_TEMPLATE_ID')) THEN
