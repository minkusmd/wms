   WMS - Sistem nou de ATRIBUTE / FILTRE / VARIATII pentru produse
   NEURON Grup SRL

   Tabele noi:
     TS_ATTRIBUTE            - dictionar de atribute, per tip de produs
     TS_ATTRIBUTE_VALUE      - valorile fiecarui atribut (liste fixe)
     TS_GOODS_ATTRIBUTE      - legatura produs <-> valoare (assignment)
     TS_GOODS_NAME_TEMPLATE  - template-uri denumire per (tip, context)

   Reguli:
     - Sistem paralel, autonom. NU se modifica TS_FILTERS* / TS_GOODS_ACNT.
     - Legatura produs->tip se face prin TS_GOODS.WEBGOODSTYPE_ID
       (FK_TS_GOODS_7) -> TS_GOODS_TYPE.GOODSTYPEID.
     - Sablon generator/trigger preluat din TRG_TS_FILTERS_BI.

   IMPORTANT: a se rula MAI INTAI pe o baza de TEST.
   ============================================================================ */

/* ============================================================================
   CLEANUP - stergere obiecte daca exista (re-rulare dupa o rulare partiala).
   Ordine: triggere -> FK circular -> tabele -> generatoare.
