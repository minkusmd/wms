EXECUTE BLOCK AS BEGIN
  IF (EXISTS(SELECT 1 FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'TS_ATTRIBUTE_VALUE')) THEN
    EXECUTE STATEMENT 'DROP TABLE TS_ATTRIBUTE_VALUE';
