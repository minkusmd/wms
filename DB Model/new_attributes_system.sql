/* ---------- Generatoare (sequences) ---------- */
CREATE SEQUENCE SQ_TS_ATTRIBUTE_ID;
CREATE SEQUENCE SQ_TS_ATTRIBUTE_VALUE_ID;
CREATE SEQUENCE SQ_TS_GOODS_NAME_TEMPLATE_ID;

/* ---------- TS_ATTRIBUTE ---------- */
CREATE TABLE TS_ATTRIBUTE (
    ATTRID          INTEGER   NOT NULL,
    GOODS_TYPE_ID   INTEGER   NOT NULL,   /* -> TS_GOODS_TYPE.GOODSTYPEID */
    NAME_RO         VARCHAR(512),         /* denumire atribut RO */
    NAME_RU         VARCHAR(512),         /* denumire atribut RU */
    FLG_FILTERABLE  SMALLINT  DEFAULT 0,  /* apare ca filtru */
    FLG_VARIATION   SMALLINT  DEFAULT 0,  /* participa la formarea variatiilor */
    FLG_IN_NAME     SMALLINT  DEFAULT 0,  /* eligibil in denumire {attr:...} */
    FLG_RECOMMENDED SMALLINT  DEFAULT 0,  /* recomandat (avertisment neblocant) */
    FLG_MULTI       SMALLINT  DEFAULT 0,  /* accepta mai multe valori pe produs */
    FLG_FREE_VALUE  SMALLINT  DEFAULT 0,  /* valoare libera, fara dictionar */
    UOM_RO          VARCHAR(64),          /* unitate de masura RO (ex. ml) - doar afisare */
    UOM_RU          VARCHAR(64),          /* unitate de masura RU - doar afisare */
    DEFAULT_VALUEID INTEGER,              /* valoare implicita, -> TS_ATTRIBUTE_VALUE */
    ORDERNO         INTEGER,
    CREATED_BY      INTEGER,
    CREATED_DATE    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE TS_ATTRIBUTE
    ADD CONSTRAINT PK_TS_ATTRIBUTE PRIMARY KEY (ATTRID);
ALTER TABLE TS_ATTRIBUTE
    ADD CONSTRAINT FK_TS_ATTRIBUTE_TYPE
    FOREIGN KEY (GOODS_TYPE_ID) REFERENCES TS_GOODS_TYPE (GOODSTYPEID);

/* ---------- TS_ATTRIBUTE_VALUE ---------- */
CREATE TABLE TS_ATTRIBUTE_VALUE (
    VALUEID      INTEGER   NOT NULL,
    ATTRID       INTEGER   NOT NULL,   /* -> TS_ATTRIBUTE.ATTRID */
    VALUE_RO     VARCHAR(1024),        /* valoare RO */
    VALUE_RU     VARCHAR(1024),        /* valoare RU */
    ORDERNO      INTEGER,
    CREATED_BY   INTEGER,
    CREATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE TS_ATTRIBUTE_VALUE
    ADD CONSTRAINT PK_TS_ATTRIBUTE_VALUE PRIMARY KEY (VALUEID);
ALTER TABLE TS_ATTRIBUTE_VALUE
    ADD CONSTRAINT FK_TS_ATTR_VALUE_ATTR
    FOREIGN KEY (ATTRID) REFERENCES TS_ATTRIBUTE (ATTRID);

/* DEFAULT_VALUEID FK - adaugat dupa ce ambele tabele exista (referinta circulara) */
ALTER TABLE TS_ATTRIBUTE
    ADD CONSTRAINT FK_TS_ATTRIBUTE_DEFVAL
    FOREIGN KEY (DEFAULT_VALUEID) REFERENCES TS_ATTRIBUTE_VALUE (VALUEID);

/* ---------- TS_GOODS_ATTRIBUTE (assignment produs <-> valoare) ----------
   Valoarea aleasa (din dictionarul TS_ATTRIBUTE_VALUE) se stocheaza ca TEXT
   RO/RU direct pe produs (denormalizat, "inghetat" istoric). Dictionarul
   TS_ATTRIBUTE_VALUE ramane doar ca sursa de selectie in UI. */
CREATE TABLE TS_GOODS_ATTRIBUTE (
    GOODSID  INTEGER NOT NULL,   /* -> TS_GOODS.GOODSID */
    ATTRID   INTEGER NOT NULL,   /* -> TS_ATTRIBUTE.ATTRID */
    ORDERNO  SMALLINT DEFAULT 1 NOT NULL, /* pozitia valorii (multi-valoare); single = 1 */
    VALUE_RO VARCHAR(256),       /* text ales din TS_ATTRIBUTE_VALUE (RO) */
    VALUE_RU VARCHAR(256)        /* text ales din TS_ATTRIBUTE_VALUE (RU) */
);
ALTER TABLE TS_GOODS_ATTRIBUTE
    ADD CONSTRAINT PK_TS_GOODS_ATTRIBUTE PRIMARY KEY (GOODSID, ATTRID, ORDERNO);
ALTER TABLE TS_GOODS_ATTRIBUTE
    ADD CONSTRAINT FK_TS_GOODS_ATTR_GOODS
    FOREIGN KEY (GOODSID) REFERENCES TS_GOODS (GOODSID);
ALTER TABLE TS_GOODS_ATTRIBUTE
    ADD CONSTRAINT FK_TS_GOODS_ATTR_ATTR
    FOREIGN KEY (ATTRID) REFERENCES TS_ATTRIBUTE (ATTRID);

/* ---------- TS_GOODS_NAME_TEMPLATE (template denumire per tip+context) ---------- */
/* CONTEXT: 1 = catalog/web, 2 = factura, 3 = eticheta/raft */
CREATE TABLE TS_GOODS_NAME_TEMPLATE (
    TEMPLATEID    INTEGER  NOT NULL,
    GOODS_TYPE_ID INTEGER  NOT NULL,   /* -> TS_GOODS_TYPE.GOODSTYPEID */
    CONTEXT       SMALLINT NOT NULL,
    TEMPLATE_RO   VARCHAR(4096),
    TEMPLATE_RU   VARCHAR(4096),
    ORDERNO       INTEGER
);
ALTER TABLE TS_GOODS_NAME_TEMPLATE
    ADD CONSTRAINT PK_TS_GOODS_NAME_TEMPLATE PRIMARY KEY (TEMPLATEID);
ALTER TABLE TS_GOODS_NAME_TEMPLATE
    ADD CONSTRAINT UQ_TS_GOODS_NAME_TEMPLATE UNIQUE (GOODS_TYPE_ID, CONTEXT);
ALTER TABLE TS_GOODS_NAME_TEMPLATE
    ADD CONSTRAINT FK_TS_GNT_TYPE
    FOREIGN KEY (GOODS_TYPE_ID) REFERENCES TS_GOODS_TYPE (GOODSTYPEID);

/* ---------- Triggere BEFORE INSERT (alocare PK + ORDERNO) ---------- */
SET TERM ^ ;

CREATE OR ALTER TRIGGER TRG_TS_ATTRIBUTE_BI FOR TS_ATTRIBUTE
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.ATTRID IS NULL) THEN
        NEW.ATTRID = NEXT VALUE FOR SQ_TS_ATTRIBUTE_ID;
    IF (NEW.ORDERNO IS NULL OR NEW.ORDERNO = -1) THEN
        SELECT COALESCE(MAX(ORDERNO)+1,1) FROM TS_ATTRIBUTE
        WHERE GOODS_TYPE_ID = NEW.GOODS_TYPE_ID
        INTO NEW.ORDERNO;
    IF (NEW.CREATED_DATE IS NULL) THEN
        NEW.CREATED_DATE = CURRENT_TIMESTAMP;
END^

CREATE OR ALTER TRIGGER TRG_TS_ATTRIBUTE_VALUE_BI FOR TS_ATTRIBUTE_VALUE
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.VALUEID IS NULL) THEN
        NEW.VALUEID = NEXT VALUE FOR SQ_TS_ATTRIBUTE_VALUE_ID;
    IF (NEW.ORDERNO IS NULL OR NEW.ORDERNO = -1) THEN
        SELECT COALESCE(MAX(ORDERNO)+1,1) FROM TS_ATTRIBUTE_VALUE
        WHERE ATTRID = NEW.ATTRID
        INTO NEW.ORDERNO;
    IF (NEW.CREATED_DATE IS NULL) THEN
        NEW.CREATED_DATE = CURRENT_TIMESTAMP;
END^

CREATE OR ALTER TRIGGER TRG_TS_GOODS_NAME_TEMPLATE_BI FOR TS_GOODS_NAME_TEMPLATE
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.TEMPLATEID IS NULL) THEN
        NEW.TEMPLATEID = NEXT VALUE FOR SQ_TS_GOODS_NAME_TEMPLATE_ID;
END^

SET TERM ; ^

