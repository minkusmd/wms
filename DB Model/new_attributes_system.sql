EXECUTE BLOCK AS BEGIN
  IF (EXISTS(SELECT 1 FROM RDB$GENERATORS WHERE RDB$GENERATOR_NAME = 'SQ_TS_ATTRIBUTE_VALUE_ID')) THEN
    EXECUTE STATEMENT 'DROP SEQUENCE SQ_TS_ATTRIBUTE_VALUE_ID';
