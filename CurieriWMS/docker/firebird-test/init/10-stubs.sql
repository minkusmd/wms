/* Baza de TEST pentru CurieriWMS: stub-uri minime ale tabelelor WMS de care
   depind DB Model/supplier_pickup.sql si DB Model/dispatch_logistics.sql
   (ruleaza imediat dupa acest fisier).
   Doar coloanele folosite de aplicatie si de proceduri - NU e schema completa SW.
   Triggerele WMS (stoc, sume, perioade) lipsesc: aici se verifica fluxul
   dispeceratului, nu contabilitatea. */

CREATE EXCEPTION ERR_GENERAL_ERROR 'Eroare generala';

CREATE TABLE TS_CUSTOMER (
    CUSTOMERID       INTEGER NOT NULL,
    PARENTID         INTEGER,
    NAME             VARCHAR(255) CHARACTER SET UTF8,
    PHONE            VARCHAR(64),
    CUSTOMER_TYPE_ID INTEGER,
    FLAGS            INTEGER DEFAULT 0,
    CONSTRAINT PK_TS_CUSTOMER PRIMARY KEY (CUSTOMERID)
);

CREATE TABLE TS_GOODS (
    GOODSID        INTEGER NOT NULL,
    PARENTID       INTEGER,
    TITLE          VARCHAR(2048) CHARACTER SET UTF8,
    CODE           VARCHAR(128) CHARACTER SET UTF8,
    UMID           INTEGER DEFAULT 1,
    WARRANTY       SMALLINT DEFAULT 0,
    SERIAL_TYPE_ID INTEGER DEFAULT 4401,
    GOODS_TYPE_ID  INTEGER DEFAULT 4201,
    CONSTRAINT PK_TS_GOODS PRIMARY KEY (GOODSID)
);

CREATE TABLE TS_USERS (
    USERID     INTEGER NOT NULL,
    FULL_NAME  VARCHAR(255) CHARACTER SET UTF8,
    CUSTOMERID INTEGER,
    CONSTRAINT PK_TS_USERS PRIMARY KEY (USERID)
);

CREATE SEQUENCE SQ_TS_STOCKS_STOCKID START WITH 600;

CREATE TABLE TS_STOCKS (
    STOCKID     INTEGER NOT NULL,
    PARENTID    INTEGER,
    FLG_FOLDER  INTEGER DEFAULT 0,
    TITLE       VARCHAR(60) CHARACTER SET UTF8,
    DESCRIPTION VARCHAR(255) CHARACTER SET UTF8,
    FLAGS       INTEGER DEFAULT 0,
    ACC$MASK    INTEGER DEFAULT 0,
    CONSTRAINT PK_TS_STOCKS PRIMARY KEY (STOCKID)
);

CREATE TABLE TS_CURRENCY (
    CURRENCYID INTEGER NOT NULL,
    TITLE      VARCHAR(16),
    BNM_RATE   DOUBLE PRECISION,
    CONSTRAINT PK_TS_CURRENCY PRIMARY KEY (CURRENCYID)
);

CREATE TABLE TS_DOCTYPES_DEFVALUES (
    DOCTYPEID INTEGER NOT NULL,
    FIRMA     INTEGER NOT NULL,
    DTSC      INTEGER,
    FLG_ACNT  SMALLINT
);

CREATE TABLE TS_GOODS_FOREIGN (
    GOODSID     INTEGER NOT NULL,
    CUSTOMERID  INTEGER NOT NULL,
    GOODS_CODE  VARCHAR(128),
    PRICE0      DOUBLE PRECISION,
    CURRENCY0ID INTEGER,
    CONSTRAINT PK_TS_GOODS_FOREIGN PRIMARY KEY (GOODSID, CUSTOMERID)
);

/* peste DOCID-urile fixe din 30-seed.sql */
CREATE SEQUENCE SQ_TDB_DOCS_DOCID START WITH 10000;

CREATE TABLE TDB_DOCS (
    DOCID        INTEGER NOT NULL,
    DOCTYPEID    INTEGER,
    DATA         TIMESTAMP,
    DT           INTEGER,
    CT           INTEGER,
    DTDEP        INTEGER,
    CTDEP        INTEGER,
    DTSC         INTEGER,
    CTSC         INTEGER DEFAULT -1,
    SC2          INTEGER,
    SUMA         DOUBLE PRECISION DEFAULT 0,
    VAT          DOUBLE PRECISION DEFAULT 0,
    CURRENCYID   INTEGER,
    RATE         DOUBLE PRECISION DEFAULT 1,
    RATEUSD      DOUBLE PRECISION DEFAULT 1,
    CONTRACTID   INTEGER DEFAULT -1,
    PARENTDOCID  INTEGER DEFAULT -1,
    FLAGS        INTEGER DEFAULT 0,
    STATEID      INTEGER,
    CREATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATED_BY   INTEGER,
    ACC$MASK     INTEGER DEFAULT 0,
    CONSTRAINT PK_TDB_DOCS PRIMARY KEY (DOCID)
);

CREATE TABLE TDB_JURNAL (
    DOCID            INTEGER NOT NULL,
    DTDEP            INTEGER NOT NULL,
    CTDEP            INTEGER NOT NULL,
    GOODSCOMPLECT_ID INTEGER DEFAULT 0 NOT NULL,
    GOODSID          INTEGER NOT NULL,
    UMID             INTEGER,
    QTY              NUMERIC(15,4),
    PRICE            DOUBLE PRECISION DEFAULT 0 NOT NULL,
    SUMA             DOUBLE PRECISION DEFAULT 0 NOT NULL,
    SUMAVAT          DOUBLE PRECISION DEFAULT 0 NOT NULL,
    WARRANTY         SMALLINT,
    COST             DOUBLE PRECISION DEFAULT 0 NOT NULL,
    FLAGS            INTEGER DEFAULT 0,
    CREATED_BY       INTEGER,
    CREATED_DATE     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_TDB_JURNAL PRIMARY KEY (DOCID, DTDEP, CTDEP, GOODSCOMPLECT_ID, GOODSID)
);

CREATE TABLE TDB_DOCS_DELIVERY (
    DOCID            INTEGER NOT NULL,
    COURIERID        INTEGER,
    DELIVERY_ADDRESS VARCHAR(512) CHARACTER SET UTF8,
    DELIVERY_DATE    DATE,
    DELIVERY_TIME    VARCHAR(32),
    PHONE_NUMBER     VARCHAR(60),
    FLAGS            INTEGER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TDB_DOCS_DELIVERY PRIMARY KEY (DOCID)
);

CREATE TABLE TS_CUST_ADDR (
    ADDRID     INTEGER NOT NULL,
    CUSTOMERID INTEGER NOT NULL,
    ADDRTYPEID INTEGER,
    CITYID     INTEGER,
    STREET     VARCHAR(255) CHARACTER SET UTF8,
    CONSTRAINT PK_TS_CUST_ADDR PRIMARY KEY (ADDRID)
);

CREATE TABLE TS_CUST_PHONES (
    PHONEID     INTEGER NOT NULL,
    CUSTOMERID  INTEGER NOT NULL,
    PHONENUMBER VARCHAR(16),
    PHONETYPEID INTEGER,
    COMMENT     VARCHAR(32) CHARACTER SET UTF8,
    CONSTRAINT PK_TS_CUST_PHONES PRIMARY KEY (PHONEID)
);

SET TERM ^ ;
CREATE TRIGGER TRG_TS_STOCKS_BI FOR TS_STOCKS
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.STOCKID IS NULL) THEN
        NEW.STOCKID = NEXT VALUE FOR SQ_TS_STOCKS_STOCKID;
END^

CREATE TRIGGER TRG_TDB_DOCS_BI FOR TDB_DOCS
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
    IF (NEW.DOCID IS NULL) THEN
        NEW.DOCID = NEXT VALUE FOR SQ_TDB_DOCS_DOCID;
END^
SET TERM ; ^

COMMIT;
